class DungeonState:
    """Exploration state and action processor for 3D dungeons."""

    def __init__(
        self,
        dmap: DungeonMap,
        start_x: int = 1,
        start_y: int = 1,
        start_z: int = 0,
        start_dir: Direction = Direction.NORTH,
        party: Party | None = None,
        asset_manager: AssetManager | None = None,
        rng: random.Random | None = None,
        random_encounters: bool = True,
    ) -> None:
        self.dmap = dmap
        self.x = start_x
        self.y = start_y
        self.z = start_z
        self.dir = start_dir
        self.party = party
        self.asset_manager = asset_manager
        self.rng = rng or random.Random()
        self.random_encounters_enabled = random_encounters

        # Torch: Java DungeonScreen.java:81 `boolean isTorchOn` — a plain
        # toggle, default off when entering. There is no rounds counter and
        # no dim; the old torch_duration inheritance is gone.
        #
        # USER-DIRECTED GBC-RULES DEVIATION (2026-11-14): finite torch
        # durations (GBC dungfun2.c:852-853,962,1128,1168-1191;
        # dungfunc.c:719-734; LW UltimaDngn.c:282,192-194) — the boolean
        # internals are replaced by `torchtime` (0-255), decremented once per
        # consumed dungeon turn in `_tick_turn`; `is_torch_on` stays as a
        # boolean alias so the screen lighting reads keep working.
        self.torchtime: int = 0
        # Set by each dungeonmech pass (``_tick_turn``) that finds the party
        # on a standing fixture; the screen runs it once the command's own
        # prompts are done (``take_fixture``).
        self.fixture_due: bool = False

    # --- Torch counter (GBC torchtime; user-directed 2026-11-14 deviation) ---

    @property
    def is_torch_on(self) -> bool:
        """Torch lit: any non-zero counter (Java `isTorchOn` reads)."""
        return self.torchtime > 0

    @is_torch_on.setter
    def is_torch_on(self, value: bool) -> None:
        """Java-parity boolean writes (DungeonScreen.java:988-1004,
        1080-1085): True lights a fresh torch (the GBC doignite load —
        dungfun2.c:1168-1191), False kills the counter outright."""
        self.torchtime = 255 if value else 0

    def ignite(self) -> bool:
        """Ignite a torch (Java DungeonScreen.java:988-1004 Keys.I; GBC
        dungfun2.c:1168-1191 doignite).

        Ignition burns one torch from the first member who owns one (Java
        truth) and lights 255 (LairWare Ignite, UltimaMain.c:1955-1974), as
        max(current, 255): no light source ever shortens the light (user
        rule 2026-11-25, ledger P-18). With no torches owned the call fails
        and the caller keeps its "No Torches!" log; nothing is consumed.
        """
        if self.party is None:
            return False
        for pm in self.party.members:
            if pm.torches > 0:
                pm.torches -= 1
                self.torchtime = max(self.torchtime, 255)
                return True
        return False

    # --- Torch persistence ---------------------------------------------------

    def torch_save_data(self) -> dict:
        """Torch block for a save dict: the GBC counter under `torchtime`.

        Old boolean saves carry the Java `isTorchOn` field instead; those
        map through `apply_torch_state` (True -> a freshly lit 255).
        """
        return {"torchtime": self.torchtime}

    def apply_torch_state(self, data: dict) -> None:
        """Restore the torch from a save dict.

        Old saves keep the Java `isTorchOn` boolean (DungeonScreen.java:81):
        on = a freshly lit 255-round torch, off = 0. New saves carry
        `torchtime` directly and win when both fields are present.
        """
        if "torchtime" in data:
            self.torchtime = min(255, max(0, int(data["torchtime"])))
        else:
            self.torchtime = 255 if data.get("is_torch_on") else 0

    # --- Spell-utility routing (Java SpellUtil.java:511-608) ---

    def valid_teleport_location(self, x: int, y: int, z: int) -> bool:
        """Java DungeonScreen.validTeleportLocation (DungeonScreen.java:1220-1222):
        the only valid relocation spot is the open NOTHING tile."""
        return self.dmap.get_tile(x, y, z) == DungeonTile.NOTHING

    def _relocate_random(self, z: int) -> bool:
        """LairWare RelocateDungeon (UltimaSpellCombat.c:576-586): roll
        ``RandNum(0, 16)`` for x and y until GetXYDng reads 0 (an empty
        tile). GetXYDng (758-768) wraps 16 to 0, so 16 lands on 0 (LW keeps
        xpos 16, which every later read wraps the same way). Direction is
        kept. A level with no empty tile would hang LW's loop; the port
        then stays put (no shipped level has none)."""
        if not any(
            self.dmap.get_tile(x, y, z) == DungeonTile.NOTHING
            for y in range(self.dmap.height)
            for x in range(self.dmap.width)
        ):
            self.z = z
            return False
        while True:
            x = self.rng.randint(0, 16) % 16
            y = self.rng.randint(0, 16) % 16
            if self.valid_teleport_location(x, y, z):
                self.x = x
                self.y = y
                self.z = z
                if self.party:
                    self.party.dungeon_level = z
                return True

    def _sync_level(self) -> None:
        if self.party:
            self.party.dungeon_level = self.z

    def spell_up(self) -> DungeonEvent:
        """REC_SU / SUR_ACRON (Java SpellUtil.spellYup, SpellUtil.java:511-544):
        step a level up; from level 0 return to the overworld screen; otherwise
        relocate onto a random valid spot of the new level. Java is silent."""
        self.z -= 1
        if self.z < 0:
            self.z = 0
            self._sync_level()
            return DungeonEvent(
                type=DungeonEventType.EXIT_DUNGEON,
                x=self.x,
                y=self.y,
                z=self.z,
                tile=self.current_tile,
            )
        self._relocate_random(self.z)
        self._sync_level()
        return DungeonEvent(
            type=DungeonEventType.LADDER_UP,
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def spell_down(self) -> DungeonEvent:
        """REC_DU / DOR_ACRON (LairWare DownLevel, UltimaSpellCombat.c:588-600):
        step a level down and relocate on a random empty tile there; refused
        on the deepest level."""
        # LairWare DownLevel (UltimaSpellCombat.c:594-597): on the deepest
        # level the spell fails and the party stays (`dungeonLevel > 6`).
        if self.z >= self.dmap.levels - 1:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                x=self.x,
                y=self.y,
                z=self.z,
                tile=self.current_tile,
                success=False,
            )
        self._relocate_random(self.z + 1)
        self._sync_level()
        return DungeonEvent(
            type=DungeonEventType.LADDER_DOWN,
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def spell_teleport(self) -> DungeonEvent:
        """LIB_REC (Java SpellUtil.spellLibRec, SpellUtil.java:583-609): random
        valid spot on the *current* level."""
        self._relocate_random(self.z)
        self._sync_level()
        return DungeonEvent(
            type=DungeonEventType.MESSAGE,
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def spell_exit(self) -> DungeonEvent:
        """SEQUITU (Java SpellUtil.spellXit, SpellUtil.java:501-509): log
        "Leaving <label>!" and return to the overworld screen."""
        raw_id = getattr(self.dmap, "id", None)
        lookup_id: int | None = None
        if raw_id is not None:
            try:
                lookup_id = int(raw_id)
            except (TypeError, ValueError):
                lookup_id = MAP_NAME_TO_ID.get(str(raw_id).upper())
        label = (
            MAP_ID_TO_LABEL.get(lookup_id)
            if lookup_id is not None and lookup_id != 0
            else None
        ) or getattr(self.dmap, "name", "Dungeon")
        return DungeonEvent(
            type=DungeonEventType.EXIT_DUNGEON,
            message=f"Leaving {label}!",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    @property
    def light_spell(self) -> bool:
        """Spell-lit alias of the torch boolean.

        USER-DIRECTED GBC-RULES DEVIATION (2026-11-14): finite torch
        durations — LORUM/LUMINAE top the counter up to >= 10
        (max(10, torchtime); GBC dungfun2.c:852-853,1070-1071) and SOMINAE
        loads 235 (dungfun2.c:962); those writes go through `torchtime` in
        combat/magic.py. This boolean alias keeps the Java-truth shape
        (SpellUtil.java:89-91 and 158-161 set ``isTorchOn = True`` — the
        light spells and the torch share one flag, so pressing I
        extinguishes a spell-lit corridor the same way it extinguishes a
        torch) for callers on the old model.
        """
        return self.is_torch_on

    @light_spell.setter
    def light_spell(self, value: bool) -> None:
        self.is_torch_on = value

    @property
    def current_tile(self) -> DungeonTile:
        """Return the DungeonTile at the current player position."""
        return self.dmap.get_tile(self.x, self.y, self.z)

    # --- Navigation commands ---

    def turn_left(self) -> DungeonEvent:
        """Turn 90 degrees counter-clockwise (LairWare Left, UltimaDngn.c:396-408)."""
        return self._turn(turn_left_dir, "left")

    def turn_right(self) -> DungeonEvent:
        """Turn 90 degrees clockwise (LairWare Right, UltimaDngn.c:382-394)."""
        return self._turn(turn_right_dir, "right")

    def _turn(self, rotate, side: str) -> DungeonEvent:
        """LairWare Right/Left (UltimaDngn.c:382-408): no turning while
        standing on a door or secret door (``GetXYDng >= 0xA0`` -> NoGo).
        Either way the command ends in dungeonmech (UltimaDngn.c:172-177,
        183-209): the turn tick and the encounter roll follow."""
        tile = self.current_tile
        if tile in _DOORWAY_TILES:
            evt = DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="Not here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )
        else:
            self.dir = rotate(self.dir)
            evt = DungeonEvent(
                type=DungeonEventType.TURNED,
                message=f"Turned {side}, now facing {self.dir.name}.",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )
        return self._with_combat(evt, self._tick_turn())

    def move_forward(self) -> DungeonEvent:
        """Step one tile forward in the current viewing direction."""
        fwd, _, _ = get_relative_offsets(self.dir)
        target_x = (self.x + fwd[0]) % self.dmap.width
        target_y = (self.y + fwd[1]) % self.dmap.height
        return self._execute_move(target_x, target_y)

    def move_backward(self) -> DungeonEvent:
        """Step one tile backward without changing facing direction."""
        fwd, _, _ = get_relative_offsets(self.dir)
        target_x = (self.x - fwd[0]) % self.dmap.width
        target_y = (self.y - fwd[1]) % self.dmap.height
        return self._execute_move(target_x, target_y)

    def step(self, dir: Direction) -> DungeonEvent:
        """Step in the given direction (forward if matching, or turning and moving)."""
        if dir == self.dir:
            return self.move_forward()
        if dir == self.dir.reverse():
            return self.move_backward()
        # If stepping in another direction, face that direction and move forward
        self.dir = dir
        return self.move_forward()

    def _execute_move(self, target_x: int, target_y: int) -> DungeonEvent:
        """Validate tile traversability, update position, and apply tile effects.

        Java DungeonScreen.move (DungeonScreen.java:1052-1077): the dungeon
        block set is WALL plus FIELD_ENERGY alone — doors (plain, locked and
        secret) and the poison/fire fields pass, and the Mark of Force does
        not open dungeon energy fields (no Force branch exists in Java's
        dungeon movement).
        """
        target_tile = self.dmap.get_tile(target_x, target_y, self.z)

        if target_tile in (DungeonTile.WALL, DungeonTile.FIELD_ENERGY):
            # A blocked move still ends in dungeonmech (UltimaDngn.c:348-359,
            # 183-209): the party tick and the encounter roll still apply.
            combat_evt = self._tick_turn()
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.BLOCKED,
                    message="Blocked! You bump into a wall.",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    success=False,
                ),
                combat_evt,
            )

        # Move coordinates
        self.x = target_x
        self.y = target_y

        # LairWare trap (UltimaDngn.c:285-294) and BombTrap (UltimaMain.c:
        # 1728-1740), user ruling 2026-11-25 (ledger D-13): the tile clears;
        # the FIRST member's StealDisarmFail (RandNum(0, 255) > DEX + class
        # bonus; dead or not) decides for everyone, and a failure is
        # BombTrap: each living member takes (RandNum(0, 255) & 0x77) + 8
        # (zp[0x13] is never written, so (0 + 1) * 8).
        if target_tile == DungeonTile.PIT_TRAP:
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            try:
                if self.party is not None and self.party.members:
                    from py_exodus.world.chests import disarm_factor

                    lead = self.party.members[0]
                    if self.rng.randint(0, 255) > disarm_factor(lead):
                        for member in list(self.party.members):
                            if member.is_disabled():
                                continue
                            member.apply_damage(
                                (self.rng.randint(0, 255) & 0x77) + 8
                            )
            except PartyDeathException:
                # Java catches PartyDeathException around the move; the
                # owning DungeonScreen's post-check routes the wipe.
                pass
            # LW: the pass that springs the trap does not roll for a fight
            # (UltimaDngn.c:196-198, 285-294).
            combat_evt = self._tick_turn(roll_encounter=False)

            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.PIT_TRAP,
                    message="Pit!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # LairWare gremlins (UltimaDngn.c:319-333), user ruling 2026-11-25
        # (ledger D-14): the tile clears; a random slot RandNum(0, Party[2] -
        # 1), nothing if that member is dead or ashes; else the hundreds of
        # food (Player[32]) drop by one, floored: 150 -> 50, under 100 keeps
        # it all.
        if target_tile == DungeonTile.GREMLINS:
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            if self.party is not None and self.party.members:
                victim = self.party.members[
                    self.rng.randint(0, len(self.party.members) - 1)
                ]
                if not victim.is_disabled() and victim.food >= 100:
                    victim.food -= 100
            # LW: no fight roll on the gremlins' pass (UltimaDngn.c:319-333).
            combat_evt = self._tick_turn(roll_encounter=False)
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.GREMLINS,
                    message="Gremlins!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # Poison and fire fields: Java checkTileAffects (DungeonScreen.java
        # 1096-1104) applies POISONFIELD on FIELD_POISON and LAVA on
        # FIELD_FIRE on entering, through the unconditional
        # Party.applyEffect fan-out; the tile is neither consumed nor
        # blocking.
        if target_tile == DungeonTile.FIELD_POISON:
            try:
                tile_effects.apply_effect(
                    self.party, TileEffect.POISONFIELD, rng=self.rng
                )
            except PartyDeathException:
                pass
        elif target_tile == DungeonTile.FIELD_FIRE:
            try:
                tile_effects.apply_effect(self.party, TileEffect.LAVA, rng=self.rng)
            except PartyDeathException:
                pass

        # Normal successful step
        combat_evt = self._tick_turn()
        if combat_evt is not None:
            return combat_evt

        return DungeonEvent(
            type=DungeonEventType.MOVED,
            message="Moved forward.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=target_tile,
            moved=True,
        )

    @staticmethod
    def _with_combat(
        evt: DungeonEvent, combat_evt: DungeonEvent | None
    ) -> DungeonEvent:
        """Merge an encounter from the turn tick into the move's event: the
        move's message is kept while the event becomes the combat trigger."""
        if combat_evt is None:
            return evt
        evt.type = combat_evt.type
        evt.creature = combat_evt.creature
        return evt

    # --- Turn & Resource Management ---

    def _tick_turn(self, roll_encounter: bool = True) -> DungeonEvent | None:
        """Run the per-move finishTurn tick (DungeonScreen.java:1124-1142).

        ``Party.endTurn`` is never called while exploring a dungeon, so the
        move counter does not tick here. After the party upkeep this runs
        LairWare's encounter roll (``_encounter_roll``, UltimaDngn.c:196-209)
        and returns its COMBAT event, else None; ``roll_encounter=False``
        skips it on the pass that sprang a pit or gremlins.

        USER-DIRECTED GBC-RULES DEVIATION (2026-11-14): finite torch
        durations — every consumed dungeon turn burns one unit of `torchtime`
        (GBC dungfun2.c:852-853,962,1128,1168-1191; dungfunc.c:719-734 —
        ``if (torchtime) torchtime--;`` under the strange-winds check; LW
        UltimaDngn.c:282,192-194). Java's boolean torch has no upkeep (no
        rounds to decrement, no expiry ever) — superseded here for the GBC
        rule. At 0 the view renders dark: the screen lighting check reads
        `is_torch_on` (torchtime > 0). The torch burn precedes the party
        upkeep, mirroring GBC's move loop (dungfunc.c:719-734) where the
        counter tick runs under the tile check before the view is drawn.

        LairWare dungeonmech (UltimaDngn.c:183-193) runs AgeChars after
        every dungeon command; with Party[3] = 1 it acts on every 4th call
        (``Party.age_chars(sosaria=False)``: food, starving, poison, healing,
        mana; ledger D-01). No move is counted and the moons stand still
        (MoonGateUpdate is Sosaria only). Stopped time does not count down
        here: LW reads gTimeNegate only in FinishAll and in combat, neither
        of which a dungeon step runs. A wipe lands in the catch below and
        routes through the screen's post-move ``check_party_death()``.
        """
        if self.torchtime > 0:
            self.torchtime -= 1
        if self.party is not None:
            # AgeChars precedes the encounter roll (UltimaDngn.c:188-196).
            try:
                self.party.age_chars(sosaria=False)
            except PartyDeathException:
                pass
        if not roll_encounter:
            return None
        # dungeonmech (UltimaDngn.c:196-199): ``if (value != 0) goto
        # dngnotcombat;`` -- a fixture under the party acts instead of the
        # encounter roll, on every command (ledger D-12).
        if self.current_tile in FIXTURE_TILES:
            self.fixture_due = True
            return None
        return self._encounter_roll()

    def take_fixture(self) -> DungeonEvent | None:
        """Run the pending dungeonmech fixture (UltimaDngn.c:211-341) for
        the tile the party stands on now, or None.

        The Time Lord (case 1) and the writing (case 8) speak; the strange
        wind (case 3) puts the torch out (``gTorch = 0``). A fountain (case
        2) or the red-hot rod (case 5) returns a FOUNTAIN / MARK event with
        ``success=False``: the screen asks who drinks or touches, and the
        answers go to ``drink_fountain`` / ``touch_mark``.
        """
        if not self.fixture_due:
            return None
        self.fixture_due = False
        tile = self.current_tile
        here = {"x": self.x, "y": self.y, "z": self.z, "tile": tile}
        if tile == DungeonTile.TIME_LORD:
            return DungeonEvent(
                type=DungeonEventType.MESSAGE,
                message=(
                    "You see a vision of the Time Lord. He says... "
                    "There is only one way. Love, Sol, Moons and Death. All else fails."
                ),
                **here,
            )
        if tile == DungeonTile.MISTY_WRITINGS:
            inscription = (
                self.dmap.level_texts[self.z]
                if self.z < len(self.dmap.level_texts)
                else ""
            )
            return DungeonEvent(
                type=DungeonEventType.MESSAGE,
                message=f"Misty Writings: {inscription}",
                **here,
            )
        if tile == DungeonTile.WIND_TRAP:
            # UltimaDngn.c:280-283: ``UPrintMessage(158); gTorch = 0;``
            self.torchtime = 0
            return DungeonEvent(
                type=DungeonEventType.WIND_TRAP,
                message="Strange wind! Your torch goes out!",
                **here,
            )
        if tile in FOUNTAIN_TILES:
            return DungeonEvent(type=DungeonEventType.FOUNTAIN, success=False, **here)
        if tile in MARK_TILES:
            return DungeonEvent(type=DungeonEventType.MARK, success=False, **here)
        return None

    # --- Encounters (LairWare dungeonmech, UltimaDngn.c:196-209) ---

    def _encounter_roll(self) -> DungeonEvent | None:
        """LairWare dungeonmech (UltimaDngn.c:196-209): on an empty tile
        ``RandNum(0, 0x82 + dungeonLevel) < 128`` passes; otherwise the
        monster is ``min(RandNum(0, dungeonLevel + 2), 6)`` into Orc..Balron,
        a chest is put on the party's tile (``PutXYDng(0x40, ...)``) and the
        fight starts. A tile holding anything never rolls. LW has no
        wandering dungeon monsters (Java's were replaced)."""
        if not self.random_encounters_enabled:
            return None
        if self.current_tile != DungeonTile.NOTHING:
            return None
        if self.rng.randint(0, 0x82 + self.z) < 128:
            return None
        value = min(self.rng.randint(0, self.z + 2), 6)
        tile_name = DUNGEON_MONSTERS[value]
        creatures = getattr(self.asset_manager, "creatures", None) or {}
        creature = creatures.get(tile_name) or CreatureDef(
            id=-1, name=tile_name.capitalize(), tile=tile_name
        )
        self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.CHEST)
        return DungeonEvent(
            type=DungeonEventType.COMBAT,
            x=self.x,
            y=self.y,
            z=self.z,
            creature=creature,
            tile=DungeonTile.NOTHING,
        )

    # --- Fixture Interactions ---

    def klimb_up(self) -> DungeonEvent:
        """Ascend via ladder towards surface (z decrements towards 0).

        Ladders consume a turn (GBC ult3.c:1388-1429; LairWare agrees:
        dKlimb/dDescend fall through to dungeonmech, UltimaDngn.c:144, 183). Unlike Java's K branch
        (DungeonScreen.java:959-971), which returns false before
        finishTurn, a real climb runs the same turn tick a normal move
        runs (mademove stays 1, so the encounter roll can fire while
        standing on the ladder). Level-0 K still exits to the overworld
        unchanged — a map transition, not a consumed move.
        """
        tile = self.current_tile
        if tile not in (DungeonTile.LADDER_UP, DungeonTile.LADDER_UP_DOWN):
            # LW InvalCmd still ends in dungeonmech (UltimaDngn.c:410-438,
            # 183-209): one turn tick.
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.BLOCKED,
                    message="No ladder up here!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=tile,
                    success=False,
                ),
                self._tick_turn(),
            )

        if self.z == 0:
            # Reached surface level - exit dungeon
            return DungeonEvent(
                type=DungeonEventType.EXIT_DUNGEON,
                message="You climb out of the dungeon to the surface!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        self.z -= 1
        if self.party:
            self.party.dungeon_level = self.z

        return self._with_combat(
            DungeonEvent(
                type=DungeonEventType.LADDER_UP,
                message=f"Climbed up to level {self.z + 1}.",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            ),
            self._tick_turn(),
        )

    def klimb_down(self) -> DungeonEvent:
        """Descend via ladder deeper into the dungeon (z increments).

        Ladders consume a turn (GBC ult3.c:1388-1429; LairWare agrees:
        dKlimb/dDescend fall through to dungeonmech, UltimaDngn.c:144, 183). Unlike Java's D branch
        (DungeonScreen.java:973-981), which returns false before
        finishTurn, a real descent runs the same turn tick a normal move
        runs (mademove stays 1, so the encounter roll can fire while
        standing on the ladder).
        """
        tile = self.current_tile
        if tile not in (DungeonTile.LADDER_DOWN, DungeonTile.LADDER_UP_DOWN):
            # LW InvalCmd still ends in dungeonmech (UltimaDngn.c:410-438,
            # 183-209): one turn tick.
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.BLOCKED,
                    message="No ladder down here!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=tile,
                    success=False,
                ),
                self._tick_turn(),
            )

        # LairWare dDescend (UltimaDngn.c:410-422) has no bound: no shipped
        # level 8 holds a down ladder. Guard it anyway: there is no ninth level.
        if self.z >= self.dmap.levels - 1:
            # LW InvalCmd still ends in dungeonmech (UltimaDngn.c:410-438,
            # 183-209): one turn tick.
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.BLOCKED,
                    message="No ladder down here!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=tile,
                    success=False,
                ),
                self._tick_turn(),
            )
        self.z += 1
        if self.party:
            self.party.dungeon_level = self.z

        return self._with_combat(
            DungeonEvent(
                type=DungeonEventType.LADDER_DOWN,
                message=f"Climbed down to level {self.z + 1}.",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            ),
            self._tick_turn(),
        )

    def drink_fountain(self, member_index: int = 0) -> DungeonEvent:
        """Inspect and drink from a dungeon fountain."""
        tile = self.current_tile
        if tile not in FOUNTAIN_TILES:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No fountain here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        member = self.party.get_member(member_index) if self.party else None
        # LairWare fountain (UltimaDngn.c:237-241): CheckAlive, else "Can't"
        # (message 153) -- the dead and ashes cannot drink.
        if member is not None and member.is_disabled():
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Can't",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if tile == DungeonTile.FOUNTAIN_HEAL:
            if member:
                member.hp = member.max_hp
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Ahh-Refreshing!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_CURE:
            if member:
                member.status = Status.GOOD
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Hmmm--Delicious!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_ACID:
            # USER-DIRECTED GBC-RULES DEVIATION (2026-11-14): acid is a flat
            # 25 damage through the apply_damage chokepoint and kills a
            # drinker below 26 HP (GBC dungfunc.c:1277-1310; LairWare
            # corroborates x&3 and acid=25). Damage here raises
            # PartyDeathException on a wiped party.
            if member:
                if member.hp < 26:
                    # GBC: currHP<26 means currHP=0 + status DEAD, not a
                    # 25-damage hit that stops at 0.
                    member.apply_damage(member.hp + 1)
                else:
                    member.apply_damage(25)
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Bleck--Nasty!",
                x=self.x,
                y=self.y,
                z=self.z,
                damage=25,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_POISON:
            # USER-DIRECTED GBC-RULES DEVIATION (2026-11-14): a poison
            # fountain inflicts POISONED only — no damage at all
            # (GBC dungfunc.c:1277-1310 sets status 0->1 and never touches
            # HP).
            if member and member.status == Status.GOOD:
                member.status = Status.POISONED
                return DungeonEvent(
                    type=DungeonEventType.FOUNTAIN,
                    message="Argh-Choke-Gasp!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=tile,
                )
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Hmm--No Effect!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        # Plain fountain
        return DungeonEvent(
            type=DungeonEventType.FOUNTAIN,
            message="Hmmm--No Effect!",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
            success=False,
        )

    def touch_mark(self, member_index: int = 0) -> DungeonEvent:
        """Touch and receive a mystical Mark (Kings, Fire, Snake, Force)."""
        tile = self.current_tile
        mark_tiles = (
            DungeonTile.MARK,
            DungeonTile.MARK_KINGS,
            DungeonTile.MARK_FIRE,
            DungeonTile.MARK_SNAKE,
            DungeonTile.MARK_FORCE,
        )
        if tile not in mark_tiles:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No Mark here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if tile == DungeonTile.MARK_KINGS:
            mark_idx = 0
            name = "Mark of Kings"
        elif tile == DungeonTile.MARK_FIRE:
            mark_idx = 1
            name = "Mark of Fire"
        elif tile == DungeonTile.MARK_SNAKE:
            mark_idx = 2
            name = "Mark of the Snake"
        elif tile == DungeonTile.MARK_FORCE:
            mark_idx = 3
            name = "Mark of Force"
        else:
            # USER-DIRECTED GBC-RULES DEVIATION (2026-11-14): mark type by tile x&3 (GBC
            # dungfunc.c:1355-1371; LW UltimaDngn.c:311 bits[(xpos&3)+4])
            # in GBC order 0=Force, 1=Fire, 2=Snake, 3=Kings — names follow
            # that order, and mark_idx maps onto the Java marks array
            # (0=Kings, 1=Fire, 2=Snake, 3=Force) shared with the
            # specialized branches above.
            names = ["Mark of Force", "Mark of Fire", "Mark of the Snake", "Mark of Kings"]
            mark_idx = (3, 1, 2, 0)[self.x & 3]
            name = names[self.x & 3]

        damage = 50
        member = self.party.get_member(member_index) if self.party else None
        if member is not None and member.is_dead():
            # USER-DIRECTED DEVIATION (ruling 2026-11-25; ledger D-26): LW's
            # brand case (UltimaDngn.c:300-318) has no CheckAlive; here the
            # dead take no mark and no damage.
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )
        if member:
            member.marks[mark_idx] = 1
            member.apply_damage(damage)

        return DungeonEvent(
            type=DungeonEventType.MARK,
            message=f"You touch the {name}!",
            x=self.x,
            y=self.y,
            z=self.z,
            damage=damage,
            tile=tile,
        )

    def open_chest(self, member_index: int = 0, disarm: bool = False) -> DungeonEvent:
        """Open a treasure chest found on the dungeon floor.

        Java truth: DungeonScreen.getChest (DungeonScreen.java:1224-1252)
        delegates the trap roll to Context.getChestTrapHandler unless the
        chest was disarmed (APPAR_UNEM) and the gold to Party.getChestGold —
        both shared with the overworld via world/chests.py, so this routes
        through the same pipeline.
        """
        from py_exodus.world.chests import open_chest

        tile = self.current_tile
        if tile != DungeonTile.CHEST:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="Not Here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        member = self.party.get_member(member_index) if self.party else None
        if member is None:
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            return DungeonEvent(
                type=DungeonEventType.CHEST,
                message="The Chest Holds: 0 Gold",
                x=self.x,
                y=self.y,
                z=self.z,
                gold=0,
                tile=tile,
            )

        # LairWare GetChest (UltimaMain.c:1601-1604): CheckAlive, else Incap.
        if member.is_disabled():
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="Incapacitated!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )
        result = open_chest(self.party, member, dungeon=True, disarmed=disarm)
        self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)

        return DungeonEvent(
            type=DungeonEventType.CHEST,
            message="\n".join(result),
            x=self.x,
            y=self.y,
            z=self.z,
            gold=result.gold,
            tile=tile,
        )

