def turn_left_dir(d: Direction) -> Direction:
    """Rotate direction 90 degrees counter-clockwise."""
    mapping = {
        Direction.NORTH: Direction.WEST,
        Direction.WEST: Direction.SOUTH,
        Direction.SOUTH: Direction.EAST,
        Direction.EAST: Direction.NORTH,
    }
    return mapping[d]


def turn_right_dir(d: Direction) -> Direction:
    """Rotate direction 90 degrees clockwise."""
    mapping = {
        Direction.NORTH: Direction.EAST,
        Direction.EAST: Direction.SOUTH,
        Direction.SOUTH: Direction.WEST,
        Direction.WEST: Direction.NORTH,
    }
    return mapping[d]


def get_relative_offsets(d: Direction) -> tuple[tuple[int, int], tuple[int, int], tuple[int, int]]:
    """Return (fwd, left, right) grid offsets for the given camera direction."""
    fwd = (d.dx, d.dy)
    # Left is 90 deg CCW
    left_dir = turn_left_dir(d)
    left = (left_dir.dx, left_dir.dy)
    # Right is 90 deg CW
    right_dir = turn_right_dir(d)
    right = (right_dir.dx, right_dir.dy)
    return fwd, left, right


class DungeonCamera:
    """First-person 3D perspective wireframe corridor renderer for Ultima III dungeons.

    Java truth (DungeonScreen.java): the dungeon is a true 3D scene — every
    solid tile (WALL / DOOR / SECRET_DOOR) is a full 1x1x1 cube spanning one
    grid cell, floor at y=0, ceiling at y=1 (DungeonScreen.java:192-205,
    492-500), with a PerspectiveCamera at the party tile centre, mid-height,
    vertical fov 67 and near plane 0.1 (DungeonScreen.java:180-183).  The
    scene is symmetric in all four facings — there are no per-facing offset
    tables; the camera basis rotates with the party.  This port reproduces
    the same placement rules on a 2D canvas with a pinhole projection:

    * camera-local axes: X lateral (positive = party's right), Y up, Z depth
      along the facing; the eye sits at y=0.5 on the NEAR BOUNDARY of the
      party tile (z=0), so the corridor column ``s`` tiles ahead spans
      z [s, s+1].  This is the classic stepped dungeon-view convention (and
      the old renderer's frame table): a wall one step ahead projects to
      half-extent 56px with generous margins, the wall beside the party
      shows as a screen-edge strip, and deeper geometry shrinks hard
      (half-extents 56 / 28 / 18.7 / 14 / 11.2 px by depth) so distance is
      readable.  Java's true centre-of-tile camera would render a wall one
      tile ahead as a viewport-filling plane — accurate but unnavigable on
      a wireframe canvas.
    * FOCAL: a 0.5-unit half-tile at depth 1 projects to 56px on the 176px
      viewport, i.e. a 77-degree vertical fov bracketing Java's 67.
    * Painter's algorithm, far to near: walls-through-openings, side faces,
      corridor frames, then the terminating front face, then fixtures.
    """

    # 176x176 viewport matching the 11x11 tile viewport area
    DEFAULT_SIZE = 176

    #: Screen px a half-tile spans at depth 1 (56 = one frame step).
    FOCAL: ClassVar[float] = 112.0

    #: Java camera.near = 0.1f (DungeonScreen.java:183)
    NEAR: ClassVar[float] = 0.1

    #: Eye height: Java builds floor boxes at y=-0.5 and ceiling boxes at
    #: y=1.5, so the walkable corridor spans y in [0, 1] and the camera sits
    #: mid-height at y=0.5 (DungeonScreen.java:197, 203; currentPos y=.5).
    EYE: ClassVar[float] = 0.5

    #: How many corridor columns the lit view projects.  Java renders the
    #: whole level every frame; the torch-lit falloff (point light ~5 units)
    #: reads as roughly 6 tiles of detail.
    MAX_DEPTH: ClassVar[int] = 6

    def __init__(
        self,
        viewport_size: int = DEFAULT_SIZE,
        default_color: tuple[int, int, int] = COLOR_WHITE,
        door_color: tuple[int, int, int] = COLOR_CYAN,
        fixture_color: tuple[int, int, int] = COLOR_GREEN,
    ) -> None:
        self.viewport_size = viewport_size
        self.default_color = default_color
        self.door_color = door_color
        self.fixture_color = fixture_color

    # --- projection helpers -------------------------------------------------

    def _project(
        self,
        cx: float,
        cy: float,
        focal: float,
        lateral: float,
        height: float,
        depth: float,
    ) -> tuple[float, float]:
        """Pinhole projection of a camera-local (lateral, height, depth) point.

        depth is clamped at Java's near plane (0.1) so faces that extend
        behind the eye render from the near-plane slice outward — a wall
        beside the party (its column spans z [0, 1]) paints the strip from
        the screen edge inward exactly like the classic view.
        """
        z = max(depth, self.NEAR)
        u = cx + lateral * focal / z
        v = cy - (height - self.EYE) * focal / z
        return (u, v)

    def _half_extent(self, focal: float, depth: float) -> float:
        """On-screen half-extent of a tile-half (0.5 world units) at depth."""
        return min(0.5 * focal / max(depth, self.NEAR), 0.5 * 176)

    def _face_quad(
        self,
        cx: float,
        cy: float,
        focal: float,
        corners: list[tuple[float, float, float]],
    ) -> list[tuple[float, float]]:
        return [self._project(cx, cy, focal, *p) for p in corners]

    def _draw_face(
        self,
        surface: pygame.Surface,
        cx: float,
        cy: float,
        focal: float,
        fill: tuple[int, int, int],
        outline: tuple[int, int, int],
        seam: tuple[int, int, int],
        lat: float | None = None,
        d0: float = 0.0,
        d1: float = 0.0,
        front_plane: float | None = None,
        h0: float = 0.0,
        h1: float = 1.0,
    ) -> list[tuple[float, float]]:
        """Fill one wall face and dress it with perspective block seams.

        Either ``lat`` (a lateral face at the given X, spanning depths
        d0..d1 and heights h0..h1) or ``front_plane`` (a face we look at
        head-on at the given depth, spanning lateral -0.5..0.5).  Seams
        project like the face, so a wall one tile ahead — whose face covers
        the whole viewport at Java's 67-degree fov — still reads as a
        receding block surface instead of a flat grey fill.
        """
        hs = [h0 + i * (h1 - h0) / 4 for i in (1, 2, 3)]
        if lat is not None:
            corners = [
                (lat, h0, d0), (lat, h0, d1), (lat, h1, d1), (lat, h1, d0)
            ]
            span = (d1 - d0) / 4
            verticals = [
                [(lat, h0, d0 + i * span), (lat, h1, d0 + i * span)]
                for i in (1, 2, 3)
            ]
            horizontals = [[(lat, h, d0), (lat, h, d1)] for h in hs]
        else:
            z = front_plane if front_plane is not None else 0.5
            xs = (-0.25, 0.0, 0.25)
            corners = [(-0.5, h0, z), (0.5, h0, z), (0.5, h1, z), (-0.5, h1, z)]
            verticals = [[(x, h0, z), (x, h1, z)] for x in xs]
            horizontals = [[(-0.5, h, z), (0.5, h, z)] for h in hs]
        quad = self._face_quad(cx, cy, focal, corners)
        pygame.draw.polygon(surface, fill, quad)
        pygame.draw.lines(surface, outline, True, quad, 1)
        for seg in verticals + horizontals:
            pygame.draw.line(
                surface,
                seam,
                self._project(cx, cy, focal, *seg[0]),
                self._project(cx, cy, focal, *seg[1]),
                1,
            )
        return quad

    # --- tile helpers -------------------------------------------------------

    @staticmethod
    def _is_solid(tile: DungeonTile) -> bool:
        """Tiles that render as a full blocking cube.

        Java addBlock (DungeonScreen.java:492-591): WALL renders a full
        1x1x1 mortar box; DOOR and SECRET_DOOR render the same full box plus
        a door slab detail.  LOCKED_DOOR has no mesh in Java (its 0x00 value
        can never survive the .ult lookup anyway), so the port renders it as
        a solid door — visually informative and never an invisible blocker.
        """
        return tile in (
            DungeonTile.WALL,
            DungeonTile.DOOR,
            DungeonTile.SECRET_DOOR,
            DungeonTile.LOCKED_DOOR,
        )

    @staticmethod
    def _is_door(tile: DungeonTile) -> bool:
        return tile in (DungeonTile.DOOR, DungeonTile.SECRET_DOOR, DungeonTile.LOCKED_DOOR)

    def render_wireframe(
        self,
        surface: pygame.Surface,
        dmap: DungeonMap | None = None,
        x: int = 0,
        y: int = 0,
        z: int = 0,
        dir: Direction = Direction.NORTH,
        torch_lit: bool = False,
        max_steps: int = 4,
        *,
        dng: DungeonMap | None = None,
        wall_color: tuple[int, int, int] | None = None,
    ) -> None:
        """Project first-person perspective dungeon corridors onto surface."""
        active_map = dmap or dng
        if active_map is None:
            raise ValueError("DungeonMap instance required (pass dmap or dng).")

        w, h = surface.get_width(), surface.get_height()
        size = min(w, h)
        focal = self.FOCAL * (size / 176)
        cx, cy = w / 2, h / 2

        # Fill background with solid black
        surface.fill(COLOR_BLACK)

        # Light / torch visibility check
        # When dark, view is limited to 1 step ahead
        # Java truth: DungeonScreen.java:81 `boolean isTorchOn` — the torch is
        # a plain boolean toggle (lit vs dark); there are no rounds, no dimming
        # and no expiry. Render light follows the same binary model.
        max_depth = self.MAX_DEPTH if torch_lit else 1

        fwd, left, right = get_relative_offsets(dir)

        def tile_at(lateral_col: int, depth_col: int) -> DungeonTile:
            """Grid tile lateral_col tiles to the right (negative = left) and
            depth_col tiles ahead of the party, wrapped like Java's dungeon."""
            tx = (x + fwd[0] * depth_col + right[0] * lateral_col) % active_map.width
            ty = (y + fwd[1] * depth_col + right[1] * lateral_col) % active_map.height
            return active_map.get_tile(tx, ty, z)

        # Scan the corridor ahead: the first solid column terminates sight
        # (its front face occludes everything beyond).  A doorway stops the
        # corridor visually too — Java renders the door cube as a full wall
        # box with a slab detail.
        stop_depth = max_depth + 1
        front_tile: DungeonTile | None = None
        for s in range(1, max_depth + 1):
            t = tile_at(0, s)
            if self._is_solid(t):
                stop_depth = s
                front_tile = t
                break

        # Filled-face colours: front faces read bright, side faces darker,
        # faces glimpsed through an opening darkest — judge walls AND depth.
        # Java also renders floor/ceiling boxes for every grid tile, so the
        # eye never sees a true void: rays past a wall hit its ceiling-box
        # side face, and rays down an opening hit the side corridor's
        # floor/ceiling planes. The port paints those with darker fills.
        front_fill = (85, 85, 85)
        side_fill = (55, 55, 55)
        opening_fill = (40, 40, 40)
        floor_fill = (38, 38, 38)
        ceil_fill = (30, 30, 30)
        shadow_fill = (25, 25, 25)
        frame_col = COLOR_LIGHT_GRAY

        max_col = min(stop_depth, max_depth) - 1  # last column with open corridor

        def quad_for(corners: list[tuple[float, float, float]]):
            return self._face_quad(cx, cy, focal, corners)

        for s in range(max_col, -1, -1):  # far to near
            plane_near = s
            plane_far = s + 1

            # --- corridor floor and ceiling strips (y=0 / y=1 planes)
            floor_quad = quad_for(
                [(-0.5, 0.0, plane_near), (0.5, 0.0, plane_near),
                 (0.5, 0.0, plane_far), (-0.5, 0.0, plane_far)]
            )
            ceiling_quad = quad_for(
                [(-0.5, 1.0, plane_near), (0.5, 1.0, plane_near),
                 (0.5, 1.0, plane_far), (-0.5, 1.0, plane_far)]
            )
            pygame.draw.polygon(surface, floor_fill, floor_quad)
            pygame.draw.polygon(surface, ceil_fill, ceiling_quad)
            # longitudinal slab seams running along the corridor converge on
            # the vanishing point — the strongest depth cue in the view
            for lat_seam in (-0.25, 0.0, 0.25):
                pygame.draw.line(
                    surface, COLOR_SEAM,
                    self._project(cx, cy, focal, lat_seam, 0.0, plane_near),
                    self._project(cx, cy, focal, lat_seam, 0.0, plane_far), 1,
                )
                pygame.draw.line(
                    surface, COLOR_SEAM,
                    self._project(cx, cy, focal, lat_seam, 1.0, plane_near),
                    self._project(cx, cy, focal, lat_seam, 1.0, plane_far), 1,
                )

            # --- side geometry, left then right (side = -1 / +1)
            for side in (-1, 1):
                lat_solid = side * 0.5
                st = tile_at(side, s)
                open_side = not self._is_solid(st)

                if open_side:
                    # Side corridor floor/ceiling extending laterally to the
                    # first wall one or two tiles out.
                    boundary = lat_solid
                    for k in (2, 3):
                        if self._is_solid(tile_at(side * (k - 1), s)):
                            break
                        boundary = side * (k - 0.5)
                    # visible lateral tiles: only up to the last column that
                    # the eye can reach through the opening at this depth
                    pygame.draw.polygon(surface, floor_fill, quad_for(
                        [(lat_solid, 0.0, plane_near),
                         (boundary, 0.0, plane_near),
                         (boundary, 0.0, plane_far),
                         (lat_solid, 0.0, plane_far)]
                    ))
                    pygame.draw.polygon(surface, ceil_fill, quad_for(
                        [(lat_solid, 1.0, plane_near),
                         (boundary, 1.0, plane_near),
                         (boundary, 1.0, plane_far),
                         (lat_solid, 1.0, plane_far)]
                    ))
                    # Java floor/ceiling boxes also show their side faces
                    # below/above the planes — dark shadow wedges whose seams
                    # continue the opening's block grid.
                    self._draw_face(
                        surface, cx, cy, focal,
                        lat=lat_solid, d0=plane_near, d1=plane_far,
                        h0=1.0, h1=2.0,
                        fill=shadow_fill, outline=COLOR_DARK_GRAY,
                        seam=(75, 75, 75),
                    )
                    self._draw_face(
                        surface, cx, cy, focal,
                        lat=lat_solid, d0=plane_near, d1=plane_far,
                        h0=-1.0, h1=0.0,
                        fill=shadow_fill, outline=COLOR_DARK_GRAY,
                        seam=(75, 75, 75),
                    )

                    # first solid tile seen through the opening
                    for k in (2, 3):
                        far = tile_at(side * k, s)
                        if self._is_solid(far):
                            lat = side * (k - 0.5)
                            quad = self._draw_face(
                                surface, cx, cy, focal,
                                lat=lat, d0=plane_near, d1=plane_far,
                                fill=opening_fill, outline=COLOR_DARK_GRAY,
                                seam=COLOR_SEAM,
                            )
                            if self._is_door(far):
                                self._front_door_detail(surface, quad, far, dim=True)
                            break
                else:
                    # Solid side wall: face at the corridor plane plus the
                    # Java ceiling-box side face continuing it upward.
                    far_boundary = plane_far
                    quad = self._draw_face(
                        surface, cx, cy, focal,
                        lat=lat_solid, d0=plane_near, d1=far_boundary,
                        fill=side_fill, outline=COLOR_LIGHT_GRAY,
                        seam=COLOR_SEAM,
                    )
                    if self._is_door(st):
                        self._side_door_detail(
                            surface,
                            quad[0][0], quad[0][1], quad[3][1],
                            quad[1][0], quad[1][1], quad[2][1],
                            is_left=side < 0, tile=st,
                        )
                    self._draw_face(
                        surface, cx, cy, focal,
                        lat=lat_solid, d0=plane_near, d1=plane_far,
                        h0=1.0, h1=2.0,
                        fill=ceil_fill, outline=COLOR_DARK_GRAY,
                        seam=(75, 75, 75),
                    )

            # --- opening edges receding outward + opening far frame
            for side in (-1, 1):
                if self._is_solid(tile_at(side, s)):
                    continue
                lat = side * 0.5
                for lat_line, hgt in ((lat, 0.0), (lat, 1.0)):
                    p_near = self._project(cx, cy, focal, lat_line, hgt, plane_near)
                    p_far = self._project(cx, cy, focal, lat_line, hgt, plane_far)
                    pygame.draw.line(surface, frame_col, p_near, p_far, 1)
                p_t = self._project(cx, cy, focal, lat, 1.0, plane_far)
                p_b = self._project(cx, cy, focal, lat, 0.0, plane_far)
                pygame.draw.line(surface, frame_col, p_t, p_b, 1)

            # --- corridor cross-section frames at the far plane
            half = self._half_extent(focal, plane_far)
            pygame.draw.line(
                surface, frame_col,
                (cx - half, cy + half), (cx + half, cy + half), 1,
            )
            pygame.draw.line(
                surface, frame_col,
                (cx - half, cy - half), (cx + half, cy - half), 1,
            )
            if s + 1 <= max_col or (front_tile is not None and stop_depth == s + 1):
                half_n = self._half_extent(focal, s + 2)
                for lat_line in (-half, half):
                    for v_sgn in (-1, 1):
                        pygame.draw.line(
                            surface, frame_col,
                            (cx + lat_line, cy + v_sgn * half),
                            (cx + lat_line, cy + v_sgn * half_n), 1,
                        )

            # --- terminating front face (+ its ceiling-box face above) at
            # the near plane of the solid column stop_depth
            if s == stop_depth - 1 and front_tile is not None and stop_depth >= 1:
                zf = plane_far  # = stop_depth - 0.5
                quad = self._draw_face(
                    surface, cx, cy, focal,
                    front_plane=zf,
                    fill=front_fill, outline=COLOR_WHITE,
                    seam=COLOR_SEAM,
                )
                if self._is_door(front_tile):
                    self._front_door_detail(surface, quad, front_tile)
                self._draw_face(
                    surface, cx, cy, focal,
                    front_plane=zf, h0=1.0, h1=2.0,
                    fill=shadow_fill, outline=COLOR_DARK_GRAY,
                    seam=(75, 75, 75),
                )

        # Render dungeon fixtures along the corridor (back to front)
        for s in range(0, min(stop_depth - 1, max_depth) + 1):
            if s == 0:
                cur_x, cur_y = x, y
            else:
                cur_x = (x + fwd[0] * s) % active_map.width
                cur_y = (y + fwd[1] * s) % active_map.height

            tile = active_map.get_tile(cur_x, cur_y, z)
            self._render_fixture(surface, tile, s, cx, cy, focal)

    def _front_door_detail(
        self,
        surface: pygame.Surface,
        quad: list[tuple[float, float]],
        tile: DungeonTile,
        dim: bool = False,
    ) -> None:
        """Door panel inside a wall face we look at head-on.

        Java slab (DungeonScreen.java:574-589): a 1.04 x .85 x .6 box centred
        at y=.4 — a panel reaching floor to 0.83 height against the wall cube.
        DOOR shows the door texture; SECRET_DOOR a near-invisible dark slab;
        LOCKED_DOOR (Java-empty, port-visible) a red panel.
        """
        xs = [p[0] for p in quad]
        top = min(p[1] for p in quad)
        bottom = max(p[1] for p in quad)
        left, right = min(xs), max(xs)
        fw = right - left
        fh = bottom - top

        if tile == DungeonTile.LOCKED_DOOR:
            panel_col = COLOR_RED
        elif tile == DungeonTile.SECRET_DOOR:
            panel_col = COLOR_DARK_GRAY
        else:
            panel_col = COLOR_CYAN if not dim else COLOR_DARK_GRAY

        door_w = max(6, int(fw * 0.82))
        door_h = max(8, int(fh * 0.80))
        door_x = int(left + (fw - door_w) / 2)
        door_y = int(bottom - door_h)

        pygame.draw.rect(surface, panel_col, (door_x, door_y, door_w, door_h), 1)
        # Lintel band across the third
        beam_y = door_y + door_h // 3
        pygame.draw.line(surface, panel_col, (door_x, beam_y), (door_x + door_w, beam_y), 1)
        # Plank centre line
        mid_x = door_x + door_w // 2
        pygame.draw.line(surface, panel_col, (mid_x, door_y), (mid_x, door_y + door_h), 1)
        if tile == DungeonTile.DOOR:
            radius = max(1, int(fw / 30))
            knob_x = door_x + int(door_w * 0.8)
            knob_y = door_y + int(door_h * 0.6)
            pygame.draw.circle(surface, COLOR_YELLOW, (knob_x, knob_y), radius)

    def _side_door_detail(
        self,
        surface: pygame.Surface,
        x1: float,
        top1: float,
        bot1: float,
        x2: float,
        top2: float,
        bot2: float,
        is_left: bool,
        tile: DungeonTile,
    ) -> None:
        """Door seams on a side wall face (Java's slab barely protrudes from
        the wall cube, so the port shows an inset seam instead of a full
        trapezoid — the wall face keeps reading as solid)."""
        # Java SECRET_DOOR slab is translucent dark gray (DungeonScreen.java:
        # 577-578) — subtle seams, unlike a plain DOOR's bright panel.
        panel_col = (
            COLOR_RED if tile == DungeonTile.LOCKED_DOOR
            else COLOR_DARK_GRAY if tile == DungeonTile.SECRET_DOOR
            else self.door_color
        )
        d_x1 = int(x1 + (x2 - x1) * 0.25)
        d_x2 = int(x1 + (x2 - x1) * 0.85)

        h1 = bot1 - top1
        h2 = bot2 - top2

        door_top1 = int(bot1 - h1 * 0.75)
        door_top2 = int(bot2 - h2 * 0.75)

        door_pts = [
            (d_x1, door_top1),
            (d_x2, door_top2),
            (d_x2, bot2),
            (d_x1, bot1),
        ]
        pygame.draw.lines(surface, panel_col, True, door_pts, 1)
        # centre plank line
        pygame.draw.line(
            surface,
            panel_col,
            ((d_x1 + d_x2) // 2, (door_top1 + door_top2) // 2),
            ((d_x1 + d_x2) // 2, (bot1 + bot2) // 2),
            1,
        )

    def _draw_front_door(
        self,
        surface: pygame.Surface,
        left: int,
        top: int,
        right: int,
        bottom: int,
        tile: DungeonTile,
    ) -> None:
        """Render front-facing vector door with frame, planks, and handle."""
        w = right - left
        h = bottom - top

        door_w = max(6, int(w * 0.48))
        door_h = max(8, int(h * 0.72))
        door_x = left + (w - door_w) // 2
        door_y = bottom - door_h

        # Outer door frame
        frame_rect = (door_x, door_y, door_w, door_h)
        pygame.draw.rect(surface, self.door_color, frame_rect, 1)

        # Arch or crossbeam
        beam_y = door_y + door_h // 3
        pygame.draw.line(surface, self.door_color, (door_x, beam_y), (door_x + door_w, beam_y), 1)

        # Vertical plank line
        mid_x = door_x + door_w // 2
        pygame.draw.line(surface, self.door_color, (mid_x, door_y), (mid_x, bottom), 1)

        # Doorknob / ring handle
        knob_x = door_x + int(door_w * 0.8)
        knob_y = door_y + int(door_h * 0.6)
        radius = max(1, w // 30)
        pygame.draw.circle(surface, COLOR_YELLOW, (knob_x, knob_y), radius)

    def _draw_side_door(
        self,
        surface: pygame.Surface,
        x1: int,
        top1: int,
        bot1: int,
        x2: int,
        top2: int,
        bot2: int,
        is_left: bool,
    ) -> None:
        """Render perspective door outline on side wall."""
        # Calculate trapezoid for side door between x1 and x2
        d_x1 = int(x1 + (x2 - x1) * 0.25)
        d_x2 = int(x1 + (x2 - x1) * 0.75)

        h1 = bot1 - top1
        h2 = bot2 - top2

        door_top1 = int(bot1 - h1 * 0.7)
        door_top2 = int(bot2 - h2 * 0.7)

        door_pts = [
            (d_x1, door_top1),
            (d_x2, door_top2),
            (d_x2, bot2),
            (d_x1, bot1),
        ]
        pygame.draw.lines(surface, self.door_color, True, door_pts, 1)

    def _render_fixture(
        self,
        surface: pygame.Surface,
        tile: DungeonTile,
        step: int,
        ccx: float = 88.0,
        ccy: float = 88.0,
        focal: float | None = None,
    ) -> None:
        """Render wireframe 3D fixtures (ladders, chests, fountains, pit traps, marks).

        The fixture sits at the centre of the column ``step`` tiles ahead;
        its screen box is the tile's true projected cross-section (Java
        renders the object mesh at the tile position, so apparent size
        follows the same 1/depth perspective as the walls).
        """
        if tile in (DungeonTile.WALL, DungeonTile.NOTHING, DungeonTile.FLOOR, DungeonTile.DOOR):
            return

        f = focal if focal is not None else self.FOCAL
        # Tile centre at z = s + 0.5 (stepped convention: column s spans
        # z [s, s+1]); the party's own tile still uses its near boundary so
        # the box stays finite (the old full-screen box).
        half = self._half_extent(f, step + 0.5)
        left, top = ccx - half, ccy - half
        right, bottom = ccx + half, ccy + half
        cx = (left + right) // 2
        w = right - left
        h = bottom - top

        if tile == DungeonTile.LADDER_UP:
            self._draw_ladder(surface, cx, bottom, top, w, h, up=True, down=False)
        elif tile == DungeonTile.LADDER_DOWN:
            self._draw_ladder(surface, cx, bottom, top, w, h, up=False, down=True)
        elif tile == DungeonTile.LADDER_UP_DOWN:
            self._draw_ladder(surface, cx, bottom, top, w, h, up=True, down=True)
        elif tile == DungeonTile.CHEST:
            self._draw_chest(surface, cx, bottom, w, h)
        elif tile in (
            DungeonTile.FOUNTAIN_PLAIN,
            DungeonTile.FOUNTAIN_HEAL,
            DungeonTile.FOUNTAIN_ACID,
            DungeonTile.FOUNTAIN_CURE,
            DungeonTile.FOUNTAIN_POISON,
        ):
            self._draw_fountain(surface, cx, bottom, w, h, tile)
        elif tile == DungeonTile.PIT_TRAP:
            self._draw_pit_trap(surface, cx, bottom, w, h)
        elif tile in (
            DungeonTile.MARK,
            DungeonTile.MARK_KINGS,
            DungeonTile.MARK_FIRE,
            DungeonTile.MARK_FORCE,
            DungeonTile.MARK_SNAKE,
        ):
            self._draw_mark(surface, cx, bottom, w, h)
        elif tile == DungeonTile.TIME_LORD:
            self._draw_time_lord(surface, cx, bottom, w, h)

    def _draw_ladder(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        top: int,
        w: int,
        h: int,
        up: bool,
        down: bool,
    ) -> None:
        """Render 3D wireframe ladder rails, rungs, and ceiling/floor holes."""
        rail_w = max(4, w // 5)
        x1 = cx - rail_w // 2
        x2 = cx + rail_w // 2

        y_top = top if up else (top + int(h * 0.4))
        y_bot = bottom if not down else (bottom - int(h * 0.05))

        # Side rails
        pygame.draw.line(surface, self.fixture_color, (x1, y_top), (x1, y_bot), 1)
        pygame.draw.line(surface, self.fixture_color, (x2, y_top), (x2, y_bot), 1)

        # Rungs
        num_rungs = 5
        span = y_bot - y_top
        if span > 4:
            for r in range(1, num_rungs + 1):
                ry = y_top + int(span * r / (num_rungs + 1))
                pygame.draw.line(surface, self.fixture_color, (x1, ry), (x2, ry), 1)

        # Holes in ceiling or floor
        hole_w = rail_w + max(4, w // 8)
        hole_h = max(3, h // 10)
        if up:
            pygame.draw.ellipse(
                surface,
                COLOR_CYAN,
                (cx - hole_w // 2, max(0, top - hole_h // 2), hole_w, hole_h),
                1,
            )
        if down:
            pygame.draw.ellipse(
                surface,
                COLOR_RED,
                (cx - hole_w // 2, bottom - hole_h // 2, hole_w, hole_h),
                1,
            )

    def _draw_chest(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render 3D wireframe treasure chest on the floor."""
        cw = max(8, int(w * 0.36))
        ch = max(5, int(h * 0.22))
        cd = max(3, int(h * 0.12))

        fx1 = cx - cw // 2
        fx2 = cx + cw // 2
        fy1 = bottom - ch
        fy2 = bottom

        # Front face
        pygame.draw.rect(surface, COLOR_YELLOW, (fx1, fy1, cw, ch), 1)

        # Lid perspective top face
        bx1 = fx1 + cd
        bx2 = fx2 + cd
        by1 = fy1 - cd
        pygame.draw.lines(
            surface,
            COLOR_YELLOW,
            False,
            [(fx1, fy1), (bx1, by1), (bx2, by1), (fx2, fy1)],
            1,
        )
        pygame.draw.line(surface, COLOR_YELLOW, (bx2, by1), (fx2, fy2), 1)

        # Latch
        pygame.draw.rect(surface, COLOR_WHITE, (cx - 1, fy1 + ch // 3, 3, 3))

    def _draw_fountain(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
        tile: DungeonTile,
    ) -> None:
        """Render 3D wireframe fountain with basin, pedestal, and water spout."""
        color_map = {
            DungeonTile.FOUNTAIN_HEAL: COLOR_BLUE,
            DungeonTile.FOUNTAIN_CURE: COLOR_CYAN,
            DungeonTile.FOUNTAIN_ACID: COLOR_YELLOW,
            DungeonTile.FOUNTAIN_POISON: COLOR_GREEN,
            DungeonTile.FOUNTAIN_PLAIN: COLOR_WHITE,
        }
        f_color = color_map.get(tile, COLOR_CYAN)

        bw = max(10, int(w * 0.44))
        bh = max(4, int(h * 0.18))
        pygame.draw.ellipse(surface, f_color, (cx - bw // 2, bottom - bh, bw, bh), 1)

        # Pedestal
        pw = max(4, bw // 3)
        ph = max(4, int(h * 0.25))
        pygame.draw.rect(surface, f_color, (cx - pw // 2, bottom - bh - ph, pw, ph), 1)

        # Upper basin
        uw = max(6, int(bw * 0.6))
        uh = max(3, int(bh * 0.6))
        pygame.draw.ellipse(surface, f_color, (cx - uw // 2, bottom - bh - ph - uh // 2, uw, uh), 1)

        # Spout & droplets
        spout_top = bottom - bh - ph - uh - max(3, h // 12)
        pygame.draw.line(surface, COLOR_WHITE, (cx, bottom - bh - ph), (cx, spout_top), 1)
        pygame.draw.line(surface, f_color, (cx, spout_top), (cx - uw // 3, bottom - bh - ph), 1)
        pygame.draw.line(surface, f_color, (cx, spout_top), (cx + uw // 3, bottom - bh - ph), 1)

    def _draw_pit_trap(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render 3D wireframe pit hole in the dungeon floor."""
        pw = max(8, int(w * 0.5))
        ph = max(4, int(h * 0.22))

        pts = [
            (cx - pw // 2, bottom - ph),
            (cx + pw // 2, bottom - ph),
            (cx + pw // 2 + 3, bottom),
            (cx - pw // 2 - 3, bottom),
        ]
        # Dark fill hole
        pygame.draw.polygon(surface, COLOR_BLACK, pts)
        pygame.draw.lines(surface, COLOR_RED, True, pts, 1)

        # Receding pit interior lines
        pygame.draw.line(surface, COLOR_DARK_GRAY, pts[0], (cx, bottom + ph // 2), 1)
        pygame.draw.line(surface, COLOR_DARK_GRAY, pts[1], (cx, bottom + ph // 2), 1)

    def _draw_mark(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render the 3D wireframe pedestal of a mystical Mark shrine."""
        ow = max(6, int(w * 0.28))
        oh = max(4, int(h * 0.22))
        pedestal_top = bottom - oh

        # Pedestal trapezoid
        pedestal_pts = [
            (cx - ow // 2, bottom),
            (cx + ow // 2, bottom),
            (cx + ow // 3, pedestal_top),
            (cx - ow // 3, pedestal_top),
        ]
        pygame.draw.lines(surface, self.default_color, True, pedestal_pts, 1)

        # Sparkle above the pedestal
        radius = max(3, w // 10)
        cy = pedestal_top - radius - 3
        pygame.draw.line(surface, COLOR_WHITE, (cx - radius, cy), (cx + radius, cy), 1)
        pygame.draw.line(surface, COLOR_WHITE, (cx, cy - radius), (cx, cy + radius), 1)

    def _draw_time_lord(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render wireframe vision of the mystical Time Lord."""
        fig_h = max(10, int(h * 0.6))
        fig_w = max(6, int(w * 0.25))

        top_y = bottom - fig_h
        head_r = max(2, fig_w // 4)

        # Head
        pygame.draw.circle(surface, COLOR_BLUE, (cx, top_y + head_r), head_r, 1)
        # Robe triangle
        robe_pts = [
            (cx, top_y + head_r * 2),
            (cx + fig_w // 2, bottom),
            (cx - fig_w // 2, bottom),
        ]
        pygame.draw.lines(surface, COLOR_BLUE, True, robe_pts, 1)
        # Staff
        pygame.draw.line(surface, COLOR_CYAN, (cx + fig_w // 2 + 2, top_y), (cx + fig_w // 2 + 2, bottom), 1)


class DungeonState:
    """Exploration state and action processor for 3D dungeons."""

    def __init__(
        self,
        dmap: DungeonMap,
        start_x: int = 1,
        start_y: int = 1,
        start_z: int = 0,
        start_dir: Direction = Direction.NORTH,
        party: Party | None = None,
        asset_manager: AssetManager | None = None,
        rng: random.Random | None = None,
        random_encounters: bool = True,
    ) -> None:
        self.dmap = dmap
        self.x = start_x
        self.y = start_y
        self.z = start_z
        self.dir = start_dir
        self.party = party
        self.asset_manager = asset_manager
        self.rng = rng or random.Random()
        self.random_encounters_enabled = random_encounters

        # Wandering monsters loose on the current level
        # (DungeonScreen.java:1255-1330): spawned by the finishTurn roll,
        # moved toward the avatar, cleaned up on level change.
        self.wandering_creatures: list[WanderingCreature] = []

        # Torch: Java DungeonScreen.java:81 `boolean isTorchOn` — a plain
        # toggle, default off when entering. There is no rounds counter and
        # no dim; the old torch_duration inheritance is gone.
        self.is_torch_on = False

    # --- Spell-utility routing (Java SpellUtil.java:511-608) ---

    def valid_teleport_location(self, x: int, y: int, z: int) -> bool:
        """Java DungeonScreen.validTeleportLocation (DungeonScreen.java:1220-1222):
        the only valid relocation spot is the open NOTHING tile."""
        return self.dmap.get_tile(x, y, z) == DungeonTile.NOTHING

    def _relocate_random(self, z: int) -> bool:
        """Java's 32-try loop (SpellUtil.java:521-539 etc.): random x/y on the
        level, position applied on the first valid NOTHING tile. Direction is
        kept; Java only refreshes the minimap."""
        for _ in range(32):
            x = self.rng.randrange(self.dmap.width)
            y = self.rng.randrange(self.dmap.height)
            if self.valid_teleport_location(x, y, z):
                self.x = x
                self.y = y
                self.z = z
                if self.party:
                    self.party.dungeon_level = z
                return True
        self.z = z
        return False

    def _sync_level(self) -> None:
        if self.party:
            self.party.dungeon_level = self.z

    def spell_up(self) -> DungeonEvent:
        """REC_SU / SUR_ACRON (Java SpellUtil.spellYup, SpellUtil.java:511-544):
        step a level up; from level 0 return to the overworld screen; otherwise
        relocate onto a random valid spot of the new level. Java is silent."""
        self.z -= 1
        if self.z < 0:
            self.z = 0
            self._sync_level()
            return DungeonEvent(
                type=DungeonEventType.EXIT_DUNGEON,
                x=self.x,
                y=self.y,
                z=self.z,
                tile=self.current_tile,
            )
        self._relocate_random(self.z)
        self._sync_level()
        return DungeonEvent(
            type=DungeonEventType.LADDER_UP,
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def spell_down(self) -> DungeonEvent:
        """REC_DU / DOR_ACRON (Java SpellUtil.spellZdown, SpellUtil.java:546-581):
        step a level down, clamped at the deepest level without relocation
        there; otherwise relocate on a random valid spot of the new level."""
        self.z += 1
        if self.z > self.dmap.levels:
            self.z = self.dmap.levels
            self._sync_level()
            return DungeonEvent(
                type=DungeonEventType.LADDER_DOWN,
                x=self.x,
                y=self.y,
                z=self.z,
                tile=self.current_tile,
            )
        self._relocate_random(self.z)
        self._sync_level()
        return DungeonEvent(
            type=DungeonEventType.LADDER_DOWN,
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def spell_teleport(self) -> DungeonEvent:
        """LIB_REC (Java SpellUtil.spellLibRec, SpellUtil.java:583-609): random
        valid spot on the *current* level."""
        self._relocate_random(self.z)
        self._sync_level()
        return DungeonEvent(
            type=DungeonEventType.MESSAGE,
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def spell_exit(self) -> DungeonEvent:
        """SEQUITU (Java SpellUtil.spellXit, SpellUtil.java:501-509): log
        "Leaving <label>!" and return to the overworld screen."""
        return DungeonEvent(
            type=DungeonEventType.EXIT_DUNGEON,
            message=f"Leaving {self.dmap.name}!",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    @property
    def light_spell(self) -> bool:
        """Spell-lit alias of the torch boolean.

        Java truth: SpellUtil.java:89-91 (LORUM) and 158-161 (LUMINAE) both
        set ``DungeonScreen.isTorchOn = True`` — the light spells and the
        torch share the single on/off flag, so pressing I extinguishes a
        spell-lit corridor the same way it extinguishes a torch.
        """
        return self.is_torch_on

    @light_spell.setter
    def light_spell(self, value: bool) -> None:
        self.is_torch_on = value

    @property
    def current_tile(self) -> DungeonTile:
        """Return the DungeonTile at the current player position."""
        return self.dmap.get_tile(self.x, self.y, self.z)

    # --- Navigation commands ---

    def turn_left(self) -> DungeonEvent:
        """Turn 90 degrees counter-clockwise."""
        self.dir = turn_left_dir(self.dir)
        return DungeonEvent(
            type=DungeonEventType.TURNED,
            message=f"Turned left, now facing {self.dir.name}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def turn_right(self) -> DungeonEvent:
        """Turn 90 degrees clockwise."""
        self.dir = turn_right_dir(self.dir)
        return DungeonEvent(
            type=DungeonEventType.TURNED,
            message=f"Turned right, now facing {self.dir.name}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def move_forward(self) -> DungeonEvent:
        """Step one tile forward in the current viewing direction."""
        fwd, _, _ = get_relative_offsets(self.dir)
        target_x = (self.x + fwd[0]) % self.dmap.width
        target_y = (self.y + fwd[1]) % self.dmap.height
        return self._execute_move(target_x, target_y)

    def move_backward(self) -> DungeonEvent:
        """Step one tile backward without changing facing direction."""
        fwd, _, _ = get_relative_offsets(self.dir)
        target_x = (self.x - fwd[0]) % self.dmap.width
        target_y = (self.y - fwd[1]) % self.dmap.height
        return self._execute_move(target_x, target_y)

    def step(self, dir: Direction) -> DungeonEvent:
        """Step in the given direction (forward if matching, or turning and moving)."""
        if dir == self.dir:
            return self.move_forward()
        if dir == self.dir.reverse():
            return self.move_backward()
        # If stepping in another direction, face that direction and move forward
        self.dir = dir
        return self.move_forward()

    def _execute_move(self, target_x: int, target_y: int) -> DungeonEvent:
        """Validate tile traversability, update position, and apply tile effects.

        Java DungeonScreen.move (DungeonScreen.java:1052-1077): the dungeon
        block set is WALL plus FIELD_ENERGY alone — doors (plain, locked and
        secret) and the poison/fire fields pass, and the Mark of Force does
        not open dungeon energy fields (no Force branch exists in Java's
        dungeon movement).
        """
        target_tile = self.dmap.get_tile(target_x, target_y, self.z)

        if target_tile in (DungeonTile.WALL, DungeonTile.FIELD_ENERGY):
            # Java move() (DungeonScreen.java:1052-1076) runs finishTurn even
            # for a blocked move — the party tick and the wandering-creature
            # upkeep (and possibly a contact battle) still apply.
            combat_evt = self._tick_turn()
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.BLOCKED,
                    message="Blocked! You bump into a wall.",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    success=False,
                ),
                combat_evt,
            )

        # Move coordinates
        self.x = target_x
        self.y = target_y

        # Pit trap: Java DungeonScreen.checkTileAffects (1090-1095) — log
        # "Pit!", apply the LAVA effect through the unconditional
        # Party.applyEffect fan-out (16+rand(32) unless the Mark of Fire),
        # clear the tile to NOTHING. No level change and no flat damage:
        # those were invented here.
        if target_tile == DungeonTile.PIT_TRAP:
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            try:
                tile_effects.apply_effect(self.party, TileEffect.LAVA, rng=self.rng)
            except PartyDeathException:
                # Java catches PartyDeathException around the move; the
                # owning DungeonScreen's post-check routes the wipe.
                pass
            combat_evt = self._tick_turn()

            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.PIT_TRAP,
                    message="Pit!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # Wind trap: extinguishes the torch (Java DungeonScreen.java:1080-1085
        # — log "Wind extinguished your torch!", Sounds.WIND, isTorchOn =
        # false; no torchduration change — that field is dead in Java).
        if target_tile == DungeonTile.WIND_TRAP:
            self.is_torch_on = False
            combat_evt = self._tick_turn()
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.WIND_TRAP,
                    message="Wind extinguished your torch!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # Gremlins: Java checkTileAffects (DungeonScreen.java:1092-1097) logs
        # "Gremlins!" and applies the unconditional Party.applyEffect
        # (Party.java:279-283, 347-352) fan-out — food -2 per non-DEAD
        # member, tile cleared to NOTHING.
        if target_tile == DungeonTile.GREMLINS:
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            try:
                tile_effects.apply_effect(self.party, TileEffect.GREMLINS, rng=self.rng)
            except PartyDeathException:
                pass
            combat_evt = self._tick_turn()
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.GREMLINS,
                    message="Gremlins!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # Poison and fire fields: Java checkTileAffects (DungeonScreen.java
        # 1096-1104) applies POISONFIELD on FIELD_POISON and LAVA on
        # FIELD_FIRE on entering, through the unconditional
        # Party.applyEffect fan-out; the tile is neither consumed nor
        # blocking.
        if target_tile == DungeonTile.FIELD_POISON:
            try:
                tile_effects.apply_effect(
                    self.party, TileEffect.POISONFIELD, rng=self.rng
                )
            except PartyDeathException:
                pass
        elif target_tile == DungeonTile.FIELD_FIRE:
            try:
                tile_effects.apply_effect(self.party, TileEffect.LAVA, rng=self.rng)
            except PartyDeathException:
                pass

        # Misty writings: read inscription
        if target_tile == DungeonTile.MISTY_WRITINGS:
            inscription = (
                self.dmap.level_texts[self.z]
                if self.z < len(self.dmap.level_texts)
                else ""
            )
            combat_evt = self._tick_turn()
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.MESSAGE,
                    message=f"Misty Writings: {inscription}",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # Time Lord vision
        if target_tile == DungeonTile.TIME_LORD:
            combat_evt = self._tick_turn()
            msg = (
                "You see a vision of the Time Lord. He says... "
                "There is only one way. Love, Sol, Moons and Death. All else fails."
            )
            return self._with_combat(
                DungeonEvent(
                    type=DungeonEventType.MESSAGE,
                    message=msg,
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=target_tile,
                    moved=True,
                ),
                combat_evt,
            )

        # Normal successful step
        combat_evt = self._tick_turn()
        if combat_evt is not None:
            return combat_evt

        return DungeonEvent(
            type=DungeonEventType.MOVED,
            message="Moved forward.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=target_tile,
            moved=True,
        )

    @staticmethod
    def _with_combat(
        evt: DungeonEvent, combat_evt: DungeonEvent | None
    ) -> DungeonEvent:
        """Merge a wandering-creature battle into the move's tile event.

        Java runs checkTileAffects and then finishTurn inside one move, so a
        creature reaching the avatar raises the battle in the same turn as
        the tile effect. The tile message is kept while the event becomes
        the combat trigger — type, creature AND the wandering instance
        (DungeonScreen.battleWandering's cr) are carried through, since
        endCombat needs it to remove the encounter and drop any chest.
        """
        if combat_evt is None:
            return evt
        evt.type = combat_evt.type
        evt.creature = combat_evt.creature
        evt.wandering = combat_evt.wandering
        return evt

    # --- Turn & Resource Management ---

    def _tick_turn(self) -> DungeonEvent | None:
        """Run the per-move finishTurn tick (DungeonScreen.java:1124-1142).

        Java truth: finishTurn runs ``getAura().passTurn()`` +
        creatureCleanup + the spawn roll + moveDungeonCreatures ONLY.
        ``Party.endTurn`` is NEVER called while exploring a dungeon — it
        runs only from GameScreen.java:712 and CombatScreen.java:472 — so
        submorsel drain, food loss and the move counter do not tick per
        dungeon move, and the torch boolean needs no upkeep (no rounds to
        decrement, no expiry ever). After the aura pass this runs the
        wandering-creature upkeep and returns a COMBAT event when a
        creature reaches the avatar (battleWandering), else None.

        USER-DIRECTED ORIGINAL-RULES DEVIATION (2026-11-10): Java's dungeon
        tick regenerates NOTHING, but the original-rules regen
        (``Party.tick_regen`` — mana +1 per 4 turns underground, HP +1 per
        4 turns, poison -1 HP per turn, starvation 2/turn) applies here
        every consumed turn. Food still does NOT drain in the dungeon: no
        submorsel decrement, no meal crossing (Java truth, kept).
        """
        if self.party is not None:
            # Java order: the aura pass precedes the wandering upkeep. It
            # only decrements the aura counter, but a member death raised
            # from a future aura effect must not crash the move — mirror the
            # post-routing guard the other tick paths carry.
            try:
                self.party.tick_regen(surface=False)
                self.party.aura.pass_turn()
            except PartyDeathException:
                pass
        return self._update_wandering_creatures()

    # --- Wandering monsters (DungeonScreen.java:1255-1330) ---

    def _update_wandering_creatures(self) -> DungeonEvent | None:
        """Java creatureCleanup + spawn roll + moveDungeonCreatures.

        Returns a COMBAT event when any creature lands on the avatar's tile
        (DungeonScreen.java:1338-1340 battleWandering), else None.
        """
        # creatureCleanup (DungeonScreen.java:1221-1228): only creatures on
        # the current level survive a level change.
        self.wandering_creatures = [
            wc for wc in self.wandering_creatures if wc.level == self.z
        ]

        if self.random_encounters_enabled:
            self._spawn_wandering_creature()

        # Java finishTurn (DungeonScreen.java:1135-1141): the QUICKNESS aura
        # skips moveDungeonCreatures for the turn (spawn still applies).
        if self.party is not None and self.party.aura.get_type() == AuraType.QUICKNESS:
            return None

        combat_evt: DungeonEvent | None = None
        for wc in list(self.wandering_creatures):
            mask = self._wandering_moves_mask(wc)
            dirs = mask & self._directions_toward(wc.x, wc.y)
            if dirs:
                d = self._random_direction(dirs)
                wc.x = (wc.x + d.dx) % self.dmap.width
                wc.y = (wc.y + d.dy) % self.dmap.height

                # Java moveDungeonCreatures (DungeonScreen.java:1300-1302):
                # when getPath returns null the creature is `continue`d past —
                # the contact-battle check only runs on an actual step.
                if wc.x == self.x and wc.y == self.y and combat_evt is None:
                    combat_evt = DungeonEvent(
                        type=DungeonEventType.COMBAT,
                        x=self.x,
                        y=self.y,
                        z=self.z,
                        creature=wc.creature,
                        wandering=wc,
                        tile=self.current_tile,
                    )
        return combat_evt

    def _wandering_moves_mask(self, wc: WanderingCreature) -> int:
        """Java DungeonScreen.getValidMovesMask/addToMask (1355-1392): the
        creature may step onto a creature-walkable tile that no other
        wandering creature occupies."""
        mask = 0
        for d in (Direction.NORTH, Direction.SOUTH, Direction.EAST, Direction.WEST):
            nx = (wc.x + d.dx) % self.dmap.width
            ny = (wc.y + d.dy) % self.dmap.height
            tile = self.dmap.get_tile(nx, ny, wc.level)
            can_move = tile.creature_walkable
            if can_move:
                for other in self.wandering_creatures:
                    if (
                        other is not wc
                        and other.x == nx
                        and other.y == ny
                        and other.level == wc.level
                    ):
                        can_move = False
                        break
            if can_move:
                mask |= d.mask
        return mask

    def _directions_toward(self, from_x: int, from_y: int) -> int:
        """Java Utils.getRelativeDirection with wrap (Utils.java:354-394): the
        cardinal directions leading toward the avatar."""
        width, height = self.dmap.width, self.dmap.height
        fx, fy = from_x, from_y
        if abs(fx - self.x) > abs(fx + width - self.x):
            fx += width
        elif abs(fx - self.x) > abs(fx - width - self.x):
            fx -= width
        if abs(fy - self.y) > abs(fy + height - self.y):
            fy += height
        elif abs(fy - self.y) > abs(fy - height - self.y):
            fy -= height

        mask = 0
        if fy - self.y < 0:
            mask |= Direction.SOUTH.mask
        elif fy - self.y > 0:
            mask |= Direction.NORTH.mask
        if fx - self.x < 0:
            mask |= Direction.EAST.mask
        elif fx - self.x > 0:
            mask |= Direction.WEST.mask
        return mask

    def _random_direction(self, mask: int) -> Direction:
        """Java Direction.getRandomValidDirection: one of the masked dirs."""
        valid = [
            d
            for d in (Direction.NORTH, Direction.SOUTH, Direction.EAST, Direction.WEST)
            if d.mask & mask
        ]
        return valid[self.rng.randrange(len(valid))]

    def _spawn_wandering_creature(self) -> bool:
        """Java DungeonScreen.spawnDungeonCreature (DungeonScreen.java:1272-1309)."""
        if len(self.wandering_creatures) >= MAX_WANDERING_CREATURES:
            return False

        # checkRandomDungeonCreatures (DungeonScreen.java:1262-1266): spawn
        # one time in 32 - currentLevel*2 while under the per-level cap.
        spawn_value = max(1, 32 - self.z * 2)
        if self.rng.randrange(spawn_value) != 0:
            return False

        creature = self._pick_dungeon_creature()
        if creature is None:
            return False

        for _ in range(WANDERING_SPAWN_TRIES):
            dx = self.rng.randrange(self.dmap.width)
            dy = self.rng.randrange(self.dmap.height)
            if self.dmap.get_tile(dx, dy, self.z).creature_walkable:
                self.wandering_creatures.append(
                    WanderingCreature(creature, dx, dy, self.z)
                )
                return True
        return False

    def _pick_dungeon_creature(self) -> CreatureDef | None:
        """Java CreatureSet.getRandomDungeonInstance (CreatureSet.java:42-56).

        Creatures without a ``level`` attribute default to 0 and are
        excluded (Java ``Creature.level`` field default); so are sails/swims/
        good/wont_attack creatures. Returns None — no spawn — when nothing is
        eligible: Java invents no fallback monster table.
        """
        dungeon_level = self.z + 1

        if self.asset_manager and self.asset_manager.creatures:
            eligible: dict[int, CreatureDef] = {}
            for cr in self.asset_manager.creatures.values():
                if (
                    cr.level > 0
                    and cr.level <= dungeon_level
                    and not cr.sails
                    and not cr.swims
                    and not cr.good
                    and not cr.wont_attack
                ):
                    eligible[cr.id] = cr
            eligible_list = list(eligible.values())
            if eligible_list:
                # Java: eligible.get(rand.nextInt(eligible.size()))
                return eligible_list[self.rng.randrange(len(eligible_list))]
        return None

    # --- Fixture Interactions ---

    def klimb_up(self) -> DungeonEvent:
        """Ascend via ladder towards surface (z decrements towards 0).

        Java truth: DungeonScreen.java:959-971 — the K branch steps
        currentLevel down, exits to the overworld below level 0 and returns
        false before finishTurn, so ladders never consume a turn.
        """
        tile = self.current_tile
        if tile not in (DungeonTile.LADDER_UP, DungeonTile.LADDER_UP_DOWN):
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No ladder up here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if self.z == 0:
            # Reached surface level - exit dungeon
            return DungeonEvent(
                type=DungeonEventType.EXIT_DUNGEON,
                message="You climb out of the dungeon to the surface!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        self.z -= 1
        if self.party:
            self.party.dungeon_level = self.z

        return DungeonEvent(
            type=DungeonEventType.LADDER_UP,
            message=f"Climbed up to level {self.z + 1}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
        )

    def klimb_down(self) -> DungeonEvent:
        """Descend via ladder deeper into the dungeon (z increments).

        Java truth: DungeonScreen.java:973-981 — the D branch increments
        currentLevel and only clamps when currentLevel exceeds DUNGEON_LVLS
        (Java's fixed constant 8), so a descent off the deepest playable
        grid is *accepted* and clamped one level past the last playable
        array index, never refused. The clamp here is ``dmap.levels`` — 8
        for every shipped dungeon, matching Java's DUNGEON_LVLS constant.
        K/D return false before finishTurn: no turn is consumed.
        """
        tile = self.current_tile
        if tile not in (DungeonTile.LADDER_DOWN, DungeonTile.LADDER_UP_DOWN):
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No ladder down here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        self.z += 1
        if self.z > self.dmap.levels:
            self.z = self.dmap.levels
        if self.party:
            self.party.dungeon_level = self.z

        return DungeonEvent(
            type=DungeonEventType.LADDER_DOWN,
            message=f"Climbed down to level {self.z + 1}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
        )

    def drink_fountain(self, member_index: int = 0) -> DungeonEvent:
        """Inspect and drink from a dungeon fountain."""
        tile = self.current_tile
        fountains = (
            DungeonTile.FOUNTAIN_PLAIN,
            DungeonTile.FOUNTAIN_HEAL,
            DungeonTile.FOUNTAIN_ACID,
            DungeonTile.FOUNTAIN_CURE,
            DungeonTile.FOUNTAIN_POISON,
        )
        if tile not in fountains:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No fountain here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        member = self.party.get_member(member_index) if self.party else None

        if tile == DungeonTile.FOUNTAIN_HEAL:
            if member:
                member.hp = member.max_hp
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Ahh-Refreshing!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_CURE:
            if member:
                member.status = Status.GOOD
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Hmmm--Delicious!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_ACID:
            dmg = 25
            if member:
                member.hp = max(0, member.hp - dmg)
                if member.hp == 0:
                    member.status = Status.DEAD
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Bleck--Nasty!",
                x=self.x,
                y=self.y,
                z=self.z,
                damage=dmg,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_POISON:
            dmg = 25
            if member:
                if member.status != Status.POISONED:
                    member.status = Status.POISONED
                    member.hp = max(0, member.hp - dmg)
                    if member.hp == 0:
                        member.status = Status.DEAD
                    return DungeonEvent(
                        type=DungeonEventType.FOUNTAIN,
                        message="Argh-Choke-Gasp!",
                        x=self.x,
                        y=self.y,
                        z=self.z,
                        damage=dmg,
                        tile=tile,
                    )
                return DungeonEvent(
                    type=DungeonEventType.FOUNTAIN,
                    message="Hmm--No Effect!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=tile,
                    success=False,
                )

        # Plain fountain
        return DungeonEvent(
            type=DungeonEventType.FOUNTAIN,
            message="Hmmm--No Effect!",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
            success=False,
        )

    def touch_mark(self, member_index: int = 0) -> DungeonEvent:
        """Touch and receive a mystical Mark (Kings, Fire, Snake, Force)."""
        tile = self.current_tile
        mark_tiles = (
            DungeonTile.MARK,
            DungeonTile.MARK_KINGS,
            DungeonTile.MARK_FIRE,
            DungeonTile.MARK_SNAKE,
            DungeonTile.MARK_FORCE,
        )
        if tile not in mark_tiles:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No Mark here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if tile == DungeonTile.MARK_KINGS:
            mark_idx = 0
            name = "Mark of Kings"
        elif tile == DungeonTile.MARK_FIRE:
            mark_idx = 1
            name = "Mark of Fire"
        elif tile == DungeonTile.MARK_SNAKE:
            mark_idx = 2
            name = "Mark of the Snake"
        elif tile == DungeonTile.MARK_FORCE:
            mark_idx = 3
            name = "Mark of Force"
        else:
            # Generic MARK: determine by dungeon level
            mark_idx = self.z % 4
            names = ["Mark of Kings", "Mark of Fire", "Mark of the Snake", "Mark of Force"]
            name = names[mark_idx]

        damage = 50
        member = self.party.get_member(member_index) if self.party else None
        if member:
            member.marks[mark_idx] = 1
            member.hp = max(0, member.hp - damage)
            if member.hp == 0:
                member.status = Status.DEAD

        return DungeonEvent(
            type=DungeonEventType.MARK,
            message=f"You touch the {name}!",
            x=self.x,
            y=self.y,
            z=self.z,
            damage=damage,
            tile=tile,
        )

    def open_chest(self, member_index: int = 0, disarm: bool = False) -> DungeonEvent:
        """Open a treasure chest found on the dungeon floor.

        Java truth: DungeonScreen.getChest (DungeonScreen.java:1224-1252)
        delegates the trap roll to Context.getChestTrapHandler unless the
        chest was disarmed (APPAR_UNEM) and the gold to Party.getChestGold —
        both shared with the overworld via world/chests.py, so this routes
        through the same pipeline.
        """
        from py_exodus.world.chests import open_chest

        tile = self.current_tile
        if tile != DungeonTile.CHEST:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="Not Here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        member = self.party.get_member(member_index) if self.party else None
        if member is None:
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            return DungeonEvent(
                type=DungeonEventType.CHEST,
                message="The Chest Holds: 0 Gold",
                x=self.x,
                y=self.y,
                z=self.z,
                gold=0,
                tile=tile,
            )

        result = open_chest(self.party, member, dungeon=True, disarmed=disarm)
        self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)

        return DungeonEvent(
            type=DungeonEventType.CHEST,
            message="\n".join(result),
            x=self.x,
            y=self.y,
            z=self.z,
            gold=result.gold,
            tile=tile,
        )

