# --- Classic EGA Palette Constants ---
COLOR_BLACK = (0, 0, 0)
COLOR_WHITE = (255, 255, 255)
COLOR_CYAN = (0, 255, 255)
COLOR_GREEN = (0, 255, 0)
COLOR_YELLOW = (255, 255, 85)
COLOR_RED = (255, 85, 85)
COLOR_BLUE = (85, 85, 255)
COLOR_MAGENTA = (255, 85, 255)
COLOR_DARK_GRAY = (85, 85, 85)
COLOR_LIGHT_GRAY = (170, 170, 170)


class DungeonEventType(str, Enum):
    """Types of events generated by dungeon navigation and interactions."""

    MOVED = "moved"
    TURNED = "turned"
    BLOCKED = "blocked"
    LADDER_UP = "ladder_up"
    LADDER_DOWN = "ladder_down"
    EXIT_DUNGEON = "exit_dungeon"
    PIT_TRAP = "pit_trap"
    WIND_TRAP = "wind_trap"
    GREMLINS = "gremlins"
    FOUNTAIN = "fountain"
    MARK = "mark"
    ORB = "orb"
    CHEST = "chest"
    COMBAT = "combat"
    MESSAGE = "message"


@dataclass
class DungeonEvent:
    """Outcome of a dungeon navigation step or fixture interaction."""

    type: DungeonEventType
    message: str = ""
    x: int = 0
    y: int = 0
    z: int = 0
    creature: CreatureDef | None = None
    damage: int = 0
    gold: int = 0
    tile: DungeonTile | None = None
    success: bool = True
    moved: bool = False


def turn_left_dir(d: Direction) -> Direction:
    """Rotate direction 90 degrees counter-clockwise."""
    mapping = {
        Direction.NORTH: Direction.WEST,
        Direction.WEST: Direction.SOUTH,
        Direction.SOUTH: Direction.EAST,
        Direction.EAST: Direction.NORTH,
    }
    return mapping[d]


def turn_right_dir(d: Direction) -> Direction:
    """Rotate direction 90 degrees clockwise."""
    mapping = {
        Direction.NORTH: Direction.EAST,
        Direction.EAST: Direction.SOUTH,
        Direction.SOUTH: Direction.WEST,
        Direction.WEST: Direction.NORTH,
    }
    return mapping[d]


def get_relative_offsets(d: Direction) -> tuple[tuple[int, int], tuple[int, int], tuple[int, int]]:
    """Return (fwd, left, right) grid offsets for the given camera direction."""
    fwd = (d.dx, d.dy)
    # Left is 90 deg CCW
    left_dir = turn_left_dir(d)
    left = (left_dir.dx, left_dir.dy)
    # Right is 90 deg CW
    right_dir = turn_right_dir(d)
    right = (right_dir.dx, right_dir.dy)
    return fwd, left, right


class DungeonCamera:
    """First-person 3D perspective wireframe corridor renderer for Ultima III dungeons."""

    # 176x176 viewport matching the 11x11 tile viewport area
    DEFAULT_SIZE = 176

    # Perspective nested rectangle coordinates: (left, top, right, bottom)
    # Step 0: camera plane (full 176x176)
    # Step 1: 1 step ahead (inset 32 px)
    # Step 2: 2 steps ahead (inset 54 px)
    # Step 3: 3 steps ahead (inset 69 px)
    # Step 4: 4 steps ahead (inset 79 px)
    # Step 5: vanishing point (88, 88)
    BOXES: ClassVar[list[tuple[int, int, int, int]]] = [
        (0, 0, 175, 175),
        (32, 32, 143, 143),
        (54, 54, 121, 121),
        (69, 69, 106, 106),
        (79, 79, 96, 96),
        (88, 88, 88, 88),
    ]

    def __init__(
        self,
        viewport_size: int = DEFAULT_SIZE,
        default_color: tuple[int, int, int] = COLOR_WHITE,
        door_color: tuple[int, int, int] = COLOR_CYAN,
        fixture_color: tuple[int, int, int] = COLOR_GREEN,
    ) -> None:
        self.viewport_size = viewport_size
        self.default_color = default_color
        self.door_color = door_color
        self.fixture_color = fixture_color

    def render_wireframe(
        self,
        surface: pygame.Surface,
        dmap: DungeonMap | None = None,
        x: int = 0,
        y: int = 0,
        z: int = 0,
        dir: Direction = Direction.NORTH,
        torch_rounds: int = 0,
        light_spell: bool = False,
        max_steps: int = 4,
        *,
        dng: DungeonMap | None = None,
        wall_color: tuple[int, int, int] | None = None,
    ) -> None:
        """Project first-person perspective dungeon corridors onto surface."""
        active_map = dmap or dng
        if active_map is None:
            raise ValueError("DungeonMap instance required (pass dmap or dng).")

        line_col = wall_color or self.default_color

        # Fill background with solid black
        surface.fill(COLOR_BLACK)

        # Light / torch visibility check
        # When dark, view is limited to 1 step ahead
        if torch_rounds <= 0 and not light_spell:
            max_visible = 1
        else:
            max_visible = min(max_steps, len(self.BOXES) - 2)

        fwd, left, right = get_relative_offsets(dir)

        # Scan corridor directly ahead to find nearest front-blocking wall/door
        visible_depth = max_visible
        front_wall_tile: DungeonTile | None = None

        for step in range(1, max_visible + 1):
            check_x = (x + fwd[0] * step) % active_map.width
            check_y = (y + fwd[1] * step) % active_map.height
            t = active_map.get_tile(check_x, check_y, z)

            if t in (
                DungeonTile.WALL,
                DungeonTile.DOOR,
                DungeonTile.LOCKED_DOOR,
                DungeonTile.SECRET_DOOR,
            ):
                visible_depth = step
                front_wall_tile = t
                break

        # Render corridor segments from step 0 to visible_depth - 1
        for s in range(visible_depth):
            box_cur = self.BOXES[s]
            box_next = self.BOXES[s + 1]

            l_c, t_c, r_c, b_c = box_cur
            l_n, t_n, r_n, b_n = box_next

            # Top & bottom longitudinal corridor lines (ceiling & floor edges)
            pygame.draw.line(surface, line_col, (l_c, t_c), (l_n, t_n), 1)
            pygame.draw.line(surface, line_col, (r_c, t_c), (r_n, t_n), 1)
            pygame.draw.line(surface, line_col, (l_c, b_c), (l_n, b_n), 1)
            pygame.draw.line(surface, line_col, (r_c, b_c), (r_n, b_n), 1)

            # Left side wall or opening
            left_pos_x = (x + fwd[0] * s + left[0]) % active_map.width
            left_pos_y = (y + fwd[1] * s + left[1]) % active_map.height
            left_tile = active_map.get_tile(left_pos_x, left_pos_y, z)

            is_left_wall = left_tile in (
                DungeonTile.WALL,
                DungeonTile.LOCKED_DOOR,
                DungeonTile.SECRET_DOOR,
            )
            is_left_door = left_tile == DungeonTile.DOOR

            if is_left_wall or is_left_door:
                # Vertical dividing line at next step frame
                pygame.draw.line(surface, line_col, (l_n, t_n), (l_n, b_n), 1)
                if is_left_door:
                    self._draw_side_door(surface, l_c, t_c, b_c, l_n, t_n, b_n, is_left=True)
            else:
                # Opening to the left (side corridor)
                pygame.draw.line(surface, line_col, (l_n, t_n), (l_c, t_n), 1)
                pygame.draw.line(surface, line_col, (l_n, b_n), (l_c, b_n), 1)
                pygame.draw.line(surface, line_col, (l_n, t_n), (l_n, b_n), 1)

            # Right side wall or opening
            right_pos_x = (x + fwd[0] * s + right[0]) % active_map.width
            right_pos_y = (y + fwd[1] * s + right[1]) % active_map.height
            right_tile = active_map.get_tile(right_pos_x, right_pos_y, z)

            is_right_wall = right_tile in (
                DungeonTile.WALL,
                DungeonTile.LOCKED_DOOR,
                DungeonTile.SECRET_DOOR,
            )
            is_right_door = right_tile == DungeonTile.DOOR

            if is_right_wall or is_right_door:
                pygame.draw.line(surface, line_col, (r_n, t_n), (r_n, b_n), 1)
                if is_right_door:
                    self._draw_side_door(surface, r_c, t_c, b_c, r_n, t_n, b_n, is_left=False)
            else:
                # Opening to the right (side corridor)
                pygame.draw.line(surface, line_col, (r_n, t_n), (r_c, t_n), 1)
                pygame.draw.line(surface, line_col, (r_n, b_n), (r_c, b_n), 1)
                pygame.draw.line(surface, line_col, (r_n, t_n), (r_n, b_n), 1)

            # Transverse frame line at step boundary (ceiling and floor cross lines)
            pygame.draw.line(surface, line_col, (l_n, t_n), (r_n, t_n), 1)
            pygame.draw.line(surface, line_col, (l_n, b_n), (r_n, b_n), 1)

        # Render front wall if a wall/door terminates corridor vision
        if front_wall_tile is not None:
            s = visible_depth
            l_f, t_f, r_f, b_f = self.BOXES[s]

            # Flat-shaded black polygon to occlude wireframes behind it
            poly_points = [(l_f, t_f), (r_f, t_f), (r_f, b_f), (l_f, b_f)]
            pygame.draw.polygon(surface, COLOR_BLACK, poly_points)
            pygame.draw.lines(surface, line_col, True, poly_points, 1)

            # If front wall has a door, render vector door frame and details
            if front_wall_tile in (
                DungeonTile.DOOR,
                DungeonTile.LOCKED_DOOR,
                DungeonTile.SECRET_DOOR,
            ):
                self._draw_front_door(surface, l_f, t_f, r_f, b_f, front_wall_tile)

        # Render dungeon fixtures along the corridor (back to front)
        for s in range(visible_depth, -1, -1):
            if s == 0:
                cur_x, cur_y = x, y
            else:
                cur_x = (x + fwd[0] * s) % active_map.width
                cur_y = (y + fwd[1] * s) % active_map.height

            tile = active_map.get_tile(cur_x, cur_y, z)
            # Only render fixtures at distance s
            if s < len(self.BOXES) - 1:
                self._render_fixture(surface, tile, s)

    def _draw_front_door(
        self,
        surface: pygame.Surface,
        left: int,
        top: int,
        right: int,
        bottom: int,
        tile: DungeonTile,
    ) -> None:
        """Render front-facing vector door with frame, planks, and handle."""
        w = right - left
        h = bottom - top

        door_w = max(6, int(w * 0.48))
        door_h = max(8, int(h * 0.72))
        door_x = left + (w - door_w) // 2
        door_y = bottom - door_h

        # Outer door frame
        frame_rect = (door_x, door_y, door_w, door_h)
        pygame.draw.rect(surface, self.door_color, frame_rect, 1)

        # Arch or crossbeam
        beam_y = door_y + door_h // 3
        pygame.draw.line(surface, self.door_color, (door_x, beam_y), (door_x + door_w, beam_y), 1)

        # Vertical plank line
        mid_x = door_x + door_w // 2
        pygame.draw.line(surface, self.door_color, (mid_x, door_y), (mid_x, bottom), 1)

        # Doorknob / ring handle
        knob_x = door_x + int(door_w * 0.8)
        knob_y = door_y + int(door_h * 0.6)
        radius = max(1, w // 30)
        pygame.draw.circle(surface, COLOR_YELLOW, (knob_x, knob_y), radius)

    def _draw_side_door(
        self,
        surface: pygame.Surface,
        x1: int,
        top1: int,
        bot1: int,
        x2: int,
        top2: int,
        bot2: int,
        is_left: bool,
    ) -> None:
        """Render perspective door outline on side wall."""
        # Calculate trapezoid for side door between x1 and x2
        d_x1 = int(x1 + (x2 - x1) * 0.25)
        d_x2 = int(x1 + (x2 - x1) * 0.75)

        h1 = bot1 - top1
        h2 = bot2 - top2

        door_top1 = int(bot1 - h1 * 0.7)
        door_top2 = int(bot2 - h2 * 0.7)

        door_pts = [
            (d_x1, door_top1),
            (d_x2, door_top2),
            (d_x2, bot2),
            (d_x1, bot1),
        ]
        pygame.draw.lines(surface, self.door_color, True, door_pts, 1)

    def _render_fixture(self, surface: pygame.Surface, tile: DungeonTile, step: int) -> None:
        """Render wireframe 3D fixtures (ladders, chests, fountains, pit traps, orbs)."""
        if tile in (DungeonTile.WALL, DungeonTile.NOTHING, DungeonTile.FLOOR, DungeonTile.DOOR):
            return

        box = self.BOXES[step]
        left, top, right, bottom = box
        cx = (left + right) // 2
        w = right - left
        h = bottom - top

        if tile == DungeonTile.LADDER_UP:
            self._draw_ladder(surface, cx, bottom, top, w, h, up=True, down=False)
        elif tile == DungeonTile.LADDER_DOWN:
            self._draw_ladder(surface, cx, bottom, top, w, h, up=False, down=True)
        elif tile == DungeonTile.LADDER_UP_DOWN:
            self._draw_ladder(surface, cx, bottom, top, w, h, up=True, down=True)
        elif tile == DungeonTile.CHEST:
            self._draw_chest(surface, cx, bottom, w, h)
        elif tile in (
            DungeonTile.FOUNTAIN_PLAIN,
            DungeonTile.FOUNTAIN_HEAL,
            DungeonTile.FOUNTAIN_ACID,
            DungeonTile.FOUNTAIN_CURE,
            DungeonTile.FOUNTAIN_POISON,
        ):
            self._draw_fountain(surface, cx, bottom, w, h, tile)
        elif tile == DungeonTile.PIT_TRAP:
            self._draw_pit_trap(surface, cx, bottom, w, h)
        elif tile in (
            DungeonTile.ORB,
            DungeonTile.MARK,
            DungeonTile.MARK_KINGS,
            DungeonTile.MARK_FIRE,
            DungeonTile.MARK_FORCE,
            DungeonTile.MARK_SNAKE,
        ):
            self._draw_orb_or_mark(surface, cx, bottom, w, h, tile)
        elif tile == DungeonTile.TIME_LORD:
            self._draw_time_lord(surface, cx, bottom, w, h)

    def _draw_ladder(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        top: int,
        w: int,
        h: int,
        up: bool,
        down: bool,
    ) -> None:
        """Render 3D wireframe ladder rails, rungs, and ceiling/floor holes."""
        rail_w = max(4, w // 5)
        x1 = cx - rail_w // 2
        x2 = cx + rail_w // 2

        y_top = top if up else (top + int(h * 0.4))
        y_bot = bottom if not down else (bottom - int(h * 0.05))

        # Side rails
        pygame.draw.line(surface, self.fixture_color, (x1, y_top), (x1, y_bot), 1)
        pygame.draw.line(surface, self.fixture_color, (x2, y_top), (x2, y_bot), 1)

        # Rungs
        num_rungs = 5
        span = y_bot - y_top
        if span > 4:
            for r in range(1, num_rungs + 1):
                ry = y_top + int(span * r / (num_rungs + 1))
                pygame.draw.line(surface, self.fixture_color, (x1, ry), (x2, ry), 1)

        # Holes in ceiling or floor
        hole_w = rail_w + max(4, w // 8)
        hole_h = max(3, h // 10)
        if up:
            pygame.draw.ellipse(
                surface,
                COLOR_CYAN,
                (cx - hole_w // 2, max(0, top - hole_h // 2), hole_w, hole_h),
                1,
            )
        if down:
            pygame.draw.ellipse(
                surface,
                COLOR_RED,
                (cx - hole_w // 2, bottom - hole_h // 2, hole_w, hole_h),
                1,
            )

    def _draw_chest(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render 3D wireframe treasure chest on the floor."""
        cw = max(8, int(w * 0.36))
        ch = max(5, int(h * 0.22))
        cd = max(3, int(h * 0.12))

        fx1 = cx - cw // 2
        fx2 = cx + cw // 2
        fy1 = bottom - ch
        fy2 = bottom

        # Front face
        pygame.draw.rect(surface, COLOR_YELLOW, (fx1, fy1, cw, ch), 1)

        # Lid perspective top face
        bx1 = fx1 + cd
        bx2 = fx2 + cd
        by1 = fy1 - cd
        pygame.draw.lines(
            surface,
            COLOR_YELLOW,
            False,
            [(fx1, fy1), (bx1, by1), (bx2, by1), (fx2, fy1)],
            1,
        )
        pygame.draw.line(surface, COLOR_YELLOW, (bx2, by1), (fx2, fy2), 1)

        # Latch
        pygame.draw.rect(surface, COLOR_WHITE, (cx - 1, fy1 + ch // 3, 3, 3))

    def _draw_fountain(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
        tile: DungeonTile,
    ) -> None:
        """Render 3D wireframe fountain with basin, pedestal, and water spout."""
        color_map = {
            DungeonTile.FOUNTAIN_HEAL: COLOR_BLUE,
            DungeonTile.FOUNTAIN_CURE: COLOR_CYAN,
            DungeonTile.FOUNTAIN_ACID: COLOR_YELLOW,
            DungeonTile.FOUNTAIN_POISON: COLOR_GREEN,
            DungeonTile.FOUNTAIN_PLAIN: COLOR_WHITE,
        }
        f_color = color_map.get(tile, COLOR_CYAN)

        bw = max(10, int(w * 0.44))
        bh = max(4, int(h * 0.18))
        pygame.draw.ellipse(surface, f_color, (cx - bw // 2, bottom - bh, bw, bh), 1)

        # Pedestal
        pw = max(4, bw // 3)
        ph = max(4, int(h * 0.25))
        pygame.draw.rect(surface, f_color, (cx - pw // 2, bottom - bh - ph, pw, ph), 1)

        # Upper basin
        uw = max(6, int(bw * 0.6))
        uh = max(3, int(bh * 0.6))
        pygame.draw.ellipse(surface, f_color, (cx - uw // 2, bottom - bh - ph - uh // 2, uw, uh), 1)

        # Spout & droplets
        spout_top = bottom - bh - ph - uh - max(3, h // 12)
        pygame.draw.line(surface, COLOR_WHITE, (cx, bottom - bh - ph), (cx, spout_top), 1)
        pygame.draw.line(surface, f_color, (cx, spout_top), (cx - uw // 3, bottom - bh - ph), 1)
        pygame.draw.line(surface, f_color, (cx, spout_top), (cx + uw // 3, bottom - bh - ph), 1)

    def _draw_pit_trap(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render 3D wireframe pit hole in the dungeon floor."""
        pw = max(8, int(w * 0.5))
        ph = max(4, int(h * 0.22))

        pts = [
            (cx - pw // 2, bottom - ph),
            (cx + pw // 2, bottom - ph),
            (cx + pw // 2 + 3, bottom),
            (cx - pw // 2 - 3, bottom),
        ]
        # Dark fill hole
        pygame.draw.polygon(surface, COLOR_BLACK, pts)
        pygame.draw.lines(surface, COLOR_RED, True, pts, 1)

        # Receding pit interior lines
        pygame.draw.line(surface, COLOR_DARK_GRAY, pts[0], (cx, bottom + ph // 2), 1)
        pygame.draw.line(surface, COLOR_DARK_GRAY, pts[1], (cx, bottom + ph // 2), 1)

    def _draw_orb_or_mark(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
        tile: DungeonTile,
    ) -> None:
        """Render 3D wireframe altar/pedestal with glowing floating magical orb or mark."""
        is_orb = tile == DungeonTile.ORB
        glow_color = COLOR_MAGENTA if is_orb else COLOR_YELLOW

        ow = max(6, int(w * 0.28))
        oh = max(4, int(h * 0.22))
        pedestal_top = bottom - oh

        # Pedestal trapezoid
        pedestal_pts = [
            (cx - ow // 2, bottom),
            (cx + ow // 2, bottom),
            (cx + ow // 3, pedestal_top),
            (cx - ow // 3, pedestal_top),
        ]
        pygame.draw.lines(surface, self.default_color, True, pedestal_pts, 1)

        # Floating orb
        radius = max(3, w // 10)
        orb_cy = pedestal_top - radius - 3
        pygame.draw.circle(surface, glow_color, (cx, orb_cy), radius, 1)

        # Internal diamond or cross sparkle
        pygame.draw.line(surface, COLOR_WHITE, (cx - radius, orb_cy), (cx + radius, orb_cy), 1)
        pygame.draw.line(surface, COLOR_WHITE, (cx, orb_cy - radius), (cx, orb_cy + radius), 1)

    def _draw_time_lord(
        self,
        surface: pygame.Surface,
        cx: int,
        bottom: int,
        w: int,
        h: int,
    ) -> None:
        """Render wireframe vision of the mystical Time Lord."""
        fig_h = max(10, int(h * 0.6))
        fig_w = max(6, int(w * 0.25))

        top_y = bottom - fig_h
        head_r = max(2, fig_w // 4)

        # Head
        pygame.draw.circle(surface, COLOR_BLUE, (cx, top_y + head_r), head_r, 1)
        # Robe triangle
        robe_pts = [
            (cx, top_y + head_r * 2),
            (cx + fig_w // 2, bottom),
            (cx - fig_w // 2, bottom),
        ]
        pygame.draw.lines(surface, COLOR_BLUE, True, robe_pts, 1)
        # Staff
        pygame.draw.line(surface, COLOR_CYAN, (cx + fig_w // 2 + 2, top_y), (cx + fig_w // 2 + 2, bottom), 1)


class DungeonState:
    """Exploration state and action processor for 3D dungeons."""

    def __init__(
        self,
        dmap: DungeonMap,
        start_x: int = 1,
        start_y: int = 1,
        start_z: int = 0,
        start_dir: Direction = Direction.NORTH,
        party: Party | None = None,
        asset_manager: AssetManager | None = None,
        rng: random.Random | None = None,
        random_encounters: bool = True,
    ) -> None:
        self.dmap = dmap
        self.x = start_x
        self.y = start_y
        self.z = start_z
        self.dir = start_dir
        self.party = party
        self.asset_manager = asset_manager
        self.rng = rng or random.Random()

        # Torch rounds: inherited from party if present
        self.torch_rounds = party.torch_duration if party is not None else 0
        self.light_spell = False
        self.random_encounters_enabled = random_encounters

    @property
    def current_tile(self) -> DungeonTile:
        """Return the DungeonTile at the current player position."""
        return self.dmap.get_tile(self.x, self.y, self.z)

    # --- Navigation commands ---

    def turn_left(self) -> DungeonEvent:
        """Turn 90 degrees counter-clockwise."""
        self.dir = turn_left_dir(self.dir)
        return DungeonEvent(
            type=DungeonEventType.TURNED,
            message=f"Turned left, now facing {self.dir.name}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def turn_right(self) -> DungeonEvent:
        """Turn 90 degrees clockwise."""
        self.dir = turn_right_dir(self.dir)
        return DungeonEvent(
            type=DungeonEventType.TURNED,
            message=f"Turned right, now facing {self.dir.name}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def turn_around(self) -> DungeonEvent:
        """Turn 180 degrees to face opposite direction."""
        self.dir = self.dir.reverse()
        return DungeonEvent(
            type=DungeonEventType.TURNED,
            message=f"Turned around, now facing {self.dir.name}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=self.current_tile,
        )

    def move_forward(self) -> DungeonEvent:
        """Step one tile forward in the current viewing direction."""
        fwd, _, _ = get_relative_offsets(self.dir)
        target_x = (self.x + fwd[0]) % self.dmap.width
        target_y = (self.y + fwd[1]) % self.dmap.height
        return self._execute_move(target_x, target_y)

    def move_backward(self) -> DungeonEvent:
        """Step one tile backward without changing facing direction."""
        fwd, _, _ = get_relative_offsets(self.dir)
        target_x = (self.x - fwd[0]) % self.dmap.width
        target_y = (self.y - fwd[1]) % self.dmap.height
        return self._execute_move(target_x, target_y)

    def step(self, dir: Direction) -> DungeonEvent:
        """Step in the given direction (forward if matching, or turning and moving)."""
        if dir == self.dir:
            return self.move_forward()
        if dir == self.dir.reverse():
            return self.move_backward()
        # If stepping in another direction, face that direction and move forward
        self.dir = dir
        return self.move_forward()

    def _execute_move(self, target_x: int, target_y: int) -> DungeonEvent:
        """Validate tile traversability, update position, and apply tile effects."""
        target_tile = self.dmap.get_tile(target_x, target_y, self.z)

        # Check impassable walls and barriers
        if target_tile in (
            DungeonTile.WALL,
            DungeonTile.LOCKED_DOOR,
            DungeonTile.SECRET_DOOR,
        ):
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="Blocked! You bump into a wall.",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=target_tile,
                success=False,
            )

        # Move coordinates
        self.x = target_x
        self.y = target_y

        # Pit trap: drops player down 1 level and deals damage
        if target_tile == DungeonTile.PIT_TRAP:
            old_z = self.z
            if self.z < 7:
                self.z += 1
                if self.party:
                    self.party.dungeon_level = self.z

            damage = self._apply_party_damage(25)
            self.dmap.set_tile(self.x, self.y, old_z, DungeonTile.NOTHING)
            self._tick_turn()

            return DungeonEvent(
                type=DungeonEventType.PIT_TRAP,
                message=f"Pit! You fell to level {self.z + 1} and took {damage} damage!",
                x=self.x,
                y=self.y,
                z=self.z,
                damage=damage,
                tile=target_tile,
                moved=True,
            )

        # Wind trap: extinguishes torch
        if target_tile == DungeonTile.WIND_TRAP:
            self.torch_rounds = 0
            self.light_spell = False
            if self.party:
                self.party.torch_duration = 0
            self._tick_turn()
            return DungeonEvent(
                type=DungeonEventType.WIND_TRAP,
                message="Wind extinguished your torch!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=target_tile,
                moved=True,
            )

        # Gremlins: steal food
        if target_tile == DungeonTile.GREMLINS:
            stolen = 0
            if self.party:
                stolen = self.party.food // 2
                self.party.food -= stolen
            self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)
            self._tick_turn()
            return DungeonEvent(
                type=DungeonEventType.GREMLINS,
                message=f"Gremlins! They stole {stolen} food!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=target_tile,
                moved=True,
            )

        # Misty writings: read inscription
        if target_tile == DungeonTile.MISTY_WRITINGS:
            inscription = (
                self.dmap.level_texts[self.z]
                if self.z < len(self.dmap.level_texts)
                else ""
            )
            self._tick_turn()
            return DungeonEvent(
                type=DungeonEventType.MESSAGE,
                message=f"Misty Writings: {inscription}",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=target_tile,
                moved=True,
            )

        # Time Lord vision
        if target_tile == DungeonTile.TIME_LORD:
            self._tick_turn()
            msg = (
                "You see a vision of the Time Lord. He says... "
                "There is only one way. Love, Sol, Moons and Death. All else fails."
            )
            return DungeonEvent(
                type=DungeonEventType.MESSAGE,
                message=msg,
                x=self.x,
                y=self.y,
                z=self.z,
                tile=target_tile,
                moved=True,
            )

        # Normal successful step
        self._tick_turn()

        # Check random monster combat encounter
        encounter = self._check_random_encounter()
        if encounter is not None:
            return DungeonEvent(
                type=DungeonEventType.COMBAT,
                message=f"Ambushed by {encounter.name}!",
                x=self.x,
                y=self.y,
                z=self.z,
                creature=encounter,
                tile=target_tile,
                moved=True,
            )

        return DungeonEvent(
            type=DungeonEventType.MOVED,
            message="Moved forward.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=target_tile,
            moved=True,
        )

    # --- Turn & Resource Management ---

    def _tick_turn(self) -> None:
        """Decrement torch counters and run the per-move endTurn tick."""
        if self.torch_rounds > 0:
            self.torch_rounds -= 1
            if self.torch_rounds <= 0:
                self.light_spell = False
            if self.party:
                self.party.torch_duration = self.torch_rounds

        if self.party:
            # Java endTurn (Party.java:592-639): dungeons are non-surface
            # maps, so submorsels drain 10 per move. A wipe from tick damage
            # raises PartyDeathException; the dungeon state catches it here —
            # the owning DungeonScreen routes game over (Task 2 flow) and
            # full routing out of the dungeon is not this task's scope.
            try:
                self.party.end_turn(surface=False)
            except PartyDeathException:
                pass

    def light_torch(self, duration: int = 100) -> bool:
        """Light a torch from party inventory."""
        if self.party:
            found = False
            for pm in self.party.members:
                if pm.player.torches > 0:
                    pm.player.torches -= 1
                    found = True
                    break
            if not found:
                return False

        self.torch_rounds = duration
        if self.party:
            self.party.torch_duration = duration
        return True

    def cast_light_spell(self, duration: int = 50) -> None:
        """Activate magical illumination (LUMINA / SOMINAE)."""
        self.light_spell = True
        self.torch_rounds = max(self.torch_rounds, duration)
        if self.party:
            self.party.torch_duration = self.torch_rounds

    # --- Fixture Interactions ---

    def klimb_up(self) -> DungeonEvent:
        """Ascend via ladder towards surface (z decrements towards 0)."""
        tile = self.current_tile
        if tile not in (DungeonTile.LADDER_UP, DungeonTile.LADDER_UP_DOWN):
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No ladder up here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if self.z == 0:
            # Reached surface level - exit dungeon
            return DungeonEvent(
                type=DungeonEventType.EXIT_DUNGEON,
                message="You climb out of the dungeon to the surface!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        self.z -= 1
        if self.party:
            self.party.dungeon_level = self.z
        self._tick_turn()

        return DungeonEvent(
            type=DungeonEventType.LADDER_UP,
            message=f"Climbed up to level {self.z + 1}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
        )

    def klimb_down(self) -> DungeonEvent:
        """Descend via ladder deeper into the dungeon (z increments towards 7)."""
        tile = self.current_tile
        if tile not in (DungeonTile.LADDER_DOWN, DungeonTile.LADDER_UP_DOWN):
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No ladder down here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if self.z >= 7:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="You are at the deepest dungeon level!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        self.z += 1
        if self.party:
            self.party.dungeon_level = self.z
        self._tick_turn()

        return DungeonEvent(
            type=DungeonEventType.LADDER_DOWN,
            message=f"Climbed down to level {self.z + 1}.",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
        )

    def climb_ladder_up(self) -> DungeonEvent:
        """Alias for klimb_up()."""
        return self.klimb_up()

    def climb_ladder_down(self) -> DungeonEvent:
        """Alias for klimb_down()."""
        return self.klimb_down()

    def drink_fountain(self, member_index: int = 0) -> DungeonEvent:
        """Inspect and drink from a dungeon fountain."""
        tile = self.current_tile
        fountains = (
            DungeonTile.FOUNTAIN_PLAIN,
            DungeonTile.FOUNTAIN_HEAL,
            DungeonTile.FOUNTAIN_ACID,
            DungeonTile.FOUNTAIN_CURE,
            DungeonTile.FOUNTAIN_POISON,
        )
        if tile not in fountains:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No fountain here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        member = self.party.get_member(member_index) if self.party else None

        if tile == DungeonTile.FOUNTAIN_HEAL:
            if member:
                member.hp = member.max_hp
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Ahh-Refreshing!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_CURE:
            if member:
                member.status = Status.GOOD
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Hmmm--Delicious!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_ACID:
            dmg = 25
            if member:
                member.hp = max(0, member.hp - dmg)
                if member.hp == 0:
                    member.status = Status.DEAD
            return DungeonEvent(
                type=DungeonEventType.FOUNTAIN,
                message="Bleck--Nasty!",
                x=self.x,
                y=self.y,
                z=self.z,
                damage=dmg,
                tile=tile,
            )

        if tile == DungeonTile.FOUNTAIN_POISON:
            dmg = 25
            if member:
                if member.status != Status.POISONED:
                    member.status = Status.POISONED
                    member.hp = max(0, member.hp - dmg)
                    if member.hp == 0:
                        member.status = Status.DEAD
                    return DungeonEvent(
                        type=DungeonEventType.FOUNTAIN,
                        message="Argh-Choke-Gasp!",
                        x=self.x,
                        y=self.y,
                        z=self.z,
                        damage=dmg,
                        tile=tile,
                    )
                return DungeonEvent(
                    type=DungeonEventType.FOUNTAIN,
                    message="Hmm--No Effect!",
                    x=self.x,
                    y=self.y,
                    z=self.z,
                    tile=tile,
                    success=False,
                )

        # Plain fountain
        return DungeonEvent(
            type=DungeonEventType.FOUNTAIN,
            message="Hmmm--No Effect!",
            x=self.x,
            y=self.y,
            z=self.z,
            tile=tile,
            success=False,
        )

    def touch_mark(self, member_index: int = 0) -> DungeonEvent:
        """Touch and receive a mystical Mark (Kings, Fire, Snake, Force)."""
        tile = self.current_tile
        mark_tiles = (
            DungeonTile.MARK,
            DungeonTile.MARK_KINGS,
            DungeonTile.MARK_FIRE,
            DungeonTile.MARK_SNAKE,
            DungeonTile.MARK_FORCE,
        )
        if tile not in mark_tiles:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No Mark here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        if tile == DungeonTile.MARK_KINGS:
            mark_idx = 0
            name = "Mark of Kings"
        elif tile == DungeonTile.MARK_FIRE:
            mark_idx = 1
            name = "Mark of Fire"
        elif tile == DungeonTile.MARK_SNAKE:
            mark_idx = 2
            name = "Mark of the Snake"
        elif tile == DungeonTile.MARK_FORCE:
            mark_idx = 3
            name = "Mark of Force"
        else:
            # Generic MARK: determine by dungeon level
            mark_idx = self.z % 4
            names = ["Mark of Kings", "Mark of Fire", "Mark of the Snake", "Mark of Force"]
            name = names[mark_idx]

        damage = 50
        member = self.party.get_member(member_index) if self.party else None
        if member:
            member.marks[mark_idx] = 1
            member.hp = max(0, member.hp - damage)
            if member.hp == 0:
                member.status = Status.DEAD

        return DungeonEvent(
            type=DungeonEventType.MARK,
            message=f"You touch the {name}!",
            x=self.x,
            y=self.y,
            z=self.z,
            damage=damage,
            tile=tile,
        )

    def touch_orb(self, member_index: int = 0) -> DungeonEvent:
        """Touch the Magical Orb, boosting stats at the cost of damage."""
        tile = self.current_tile
        if tile != DungeonTile.ORB:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No Magical Orb here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        damage = 50
        member = self.party.get_member(member_index) if self.party else None
        if member:
            race = member.character.race
            member.strength = min(race.max_str, member.strength + 5)
            member.dexterity = min(race.max_dex, member.dexterity + 5)
            member.intelligence = min(race.max_int, member.intelligence + 5)
            member.wisdom = min(race.max_wis, member.wisdom + 5)
            member.hp = max(0, member.hp - damage)
            if member.hp == 0:
                member.status = Status.DEAD

        return DungeonEvent(
            type=DungeonEventType.ORB,
            message="You touch the Magical Orb! A surge of power flows through you!",
            x=self.x,
            y=self.y,
            z=self.z,
            damage=damage,
            tile=tile,
        )

    def open_chest(self, member_index: int = 0, disarm: bool = False) -> DungeonEvent:
        """Open a treasure chest found on the dungeon floor."""
        tile = self.current_tile
        if tile != DungeonTile.CHEST:
            return DungeonEvent(
                type=DungeonEventType.BLOCKED,
                message="No chest here!",
                x=self.x,
                y=self.y,
                z=self.z,
                tile=tile,
                success=False,
            )

        gold_amount = self.rng.randint(50, 150)
        damage = 0
        if not disarm and self.rng.random() < 0.35:
            # Trap triggers if not disarmed
            damage = 15
            member = self.party.get_member(member_index) if self.party else None
            if member:
                member.hp = max(0, member.hp - damage)
                if member.hp == 0:
                    member.status = Status.DEAD

        if self.party:
            # Java truth: chest gold credits the opening member's purse via
            # CharacterRecord.adjustGold (Party.getChestGold → adjustGold),
            # capped at 9999 — not a party-level pool.
            member = self.party.get_member(member_index)
            if member is not None:
                member.adjust_gold(gold_amount)
            else:
                self.party.gold += gold_amount

        self.dmap.set_tile(self.x, self.y, self.z, DungeonTile.NOTHING)

        msg = f"The Chest Holds: {gold_amount} Gold!"
        if damage > 0:
            msg += f" A trap sprang for {damage} damage!"

        return DungeonEvent(
            type=DungeonEventType.CHEST,
            message=msg,
            x=self.x,
            y=self.y,
            z=self.z,
            gold=gold_amount,
            damage=damage,
            tile=tile,
        )

    # --- Helper methods ---

    def _apply_party_damage(self, amount: int) -> int:
        """Apply damage across living party members, updating DEAD status."""
        if not self.party:
            return amount

        total = 0
        for m in self.party.living_members:
            m.hp = max(0, m.hp - amount)
            if m.hp == 0:
                m.status = Status.DEAD
            total += amount
        return total

    def _check_random_encounter(self) -> CreatureDef | None:
        """Check for random monster ambush based on dungeon level."""
        if not self.random_encounters_enabled:
            return None

        # Chance scales with depth: 32 - z * 2
        spawn_val = max(6, 32 - self.z * 2)
        if self.rng.randint(0, spawn_val - 1) != 0:
            return None

        return self._pick_dungeon_creature()

    def _pick_dungeon_creature(self) -> CreatureDef:
        """Select an eligible creature definition for current dungeon depth."""
        dungeon_level = self.z + 1

        if self.asset_manager and self.asset_manager.creatures:
            eligible: list[CreatureDef] = []
            for cr in self.asset_manager.creatures.values():
                if (
                    cr.level > 0
                    and cr.level <= dungeon_level
                    and not cr.sails
                    and not cr.swims
                    and not cr.good
                    and not cr.wont_attack
                ):
                    eligible.append(cr)
            if eligible:
                return self.rng.choice(eligible)

        # Fallback default creatures scaled by dungeon depth
        fallback_monsters = [
            CreatureDef(id=10, name="Orc", tile="orc", basehp=30, level=1, exp=3),
            CreatureDef(id=11, name="Skeleton", tile="skeleton", basehp=50, level=1, exp=4, undead=True),
            CreatureDef(id=12, name="Thief", tile="thief", basehp=80, level=2, exp=5),
            CreatureDef(id=13, name="Giant", tile="giant", basehp=80, level=3, exp=6),
            CreatureDef(id=15, name="Fighter", tile="fighter", basehp=96, level=4, exp=8),
            CreatureDef(id=14, name="Daemon", tile="daemon", basehp=135, level=5, exp=8),
            CreatureDef(id=16, name="Wizard", tile="wizard", basehp=112, level=6, exp=10),
            CreatureDef(id=17, name="Pincher", tile="pincher", basehp=144, level=7, exp=10, poisons=True),
            CreatureDef(id=18, name="Dragon", tile="dragon", basehp=228, level=8, exp=15),
        ]
        eligible = [m for m in fallback_monsters if m.level <= dungeon_level]
        return self.rng.choice(eligible or fallback_monsters[:1])
