        w = max(3, int(h * 0.5))
        head = max(1, h // 6)
        pygame.draw.circle(s, colour, (int(fx), int(fy - h + head)), head)
        pygame.draw.polygon(s, colour, [
            (fx, fy - h + 2 * head), (fx + w / 2, fy), (fx - w / 2, fy),
        ])

