"""Pixel alphabets drawn as data, for the victory ending.

No font files: every glyph is a small bitmap written out below (``#`` is
ink) and drawn with whole-pixel rectangles, so the lettering is clean and
evenly spaced at any integer scale.

- ``BLOCK``: 5x7 capitals, digits and punctuation (the victory page).
- ``TINY``: 3x5 capitals and digits (the small class and level line).
- ``LOGO``: 6x10 heavy capitals and digits for the banner words; drawn with
  :func:`render_banner` in the colours of the pyExodus title art.
- ``SERIF``: a 7x12 slab-serif face with both cases (the epilogue). Every
  glyph is 7 wide, so LairWare's 20-column lines keep their justified edges.
"""
from __future__ import annotations

from functools import lru_cache

import pygame

Colour = tuple[int, int, int]


class PixelFont:
    """A bitmap face: ``glyphs`` maps a character to its rows of ``#``/``.``."""

    def __init__(
        self,
        name: str,
        height: int,
        glyphs: dict[str, tuple[str, ...]],
        spacing: int = 1,
        space_width: int | None = None,
        upper_only: bool = False,
        fallback: str | None = None,
    ) -> None:
        self.name = name
        self.height = height
        self.spacing = spacing
        self.upper_only = upper_only
        self.glyphs = dict(glyphs)
        #: Drawn for a character the face has no glyph for (else a blank).
        self.fallback = fallback
        for ch, rows in self.glyphs.items():
            if len(rows) != height or len({len(r) for r in rows}) != 1:
                raise ValueError(f"{name}: glyph {ch!r} is not a {height}-row grid")
        widths = [len(rows[0]) for rows in self.glyphs.values()]
        self.space_width = space_width if space_width is not None else max(widths)

    def _key(self, ch: str) -> str:
        return ch.upper() if self.upper_only else ch

    def has(self, ch: str) -> bool:
        """Whether ``ch`` can be drawn (a space always can)."""
        return ch == " " or self._key(ch) in self.glyphs

    def missing(self, text: str) -> set[str]:
        """The characters of ``text`` this face has no glyph for."""
        return {ch for ch in text if not self.has(ch)}

    def _rows(self, ch: str) -> tuple[str, ...] | None:
        rows = self.glyphs.get(self._key(ch))
        if rows is None and ch != " " and self.fallback is not None:
            rows = self.glyphs.get(self.fallback)
        return rows

    def _advance(self, ch: str) -> int:
        rows = self._rows(ch)
        return len(rows[0]) if rows is not None else self.space_width

    def width(self, text: str) -> int:
        """Width of ``text`` in font pixels (no trailing spacing)."""
        if not text:
            return 0
        return sum(self._advance(ch) for ch in text) + self.spacing * (len(text) - 1)

    def ink(self, text: str) -> set[tuple[int, int]]:
        """The inked (x, y) font pixels of ``text``. A character without a
        glyph is drawn as the face's fallback, or left blank without one."""
        out: set[tuple[int, int]] = set()
        x = 0
        for ch in text:
            rows = self._rows(ch)
            if rows is not None:
                for y, row in enumerate(rows):
                    for dx, cell in enumerate(row):
                        if cell == "#":
                            out.add((x + dx, y))
            x += self._advance(ch) + self.spacing
        return out

    def render(self, text: str, colour: Colour, scale: int = 1) -> pygame.Surface:
        """``text`` in one colour on a transparent surface, each font pixel
        a ``scale`` x ``scale`` square."""
        return _render(self, text, tuple(colour[:3]), int(scale))


@lru_cache(maxsize=512)
def _render(font: PixelFont, text: str, colour: Colour, scale: int) -> pygame.Surface:
    surf = pygame.Surface(
        (max(1, font.width(text) * scale), font.height * scale), pygame.SRCALPHA
    )
    for x, y in font.ink(text):
        surf.fill(colour, (x * scale, y * scale, scale, scale))
    return surf


@lru_cache(maxsize=64)
def render_banner(
    font: PixelFont,
    text: str,
    scale: int,
    stretch: int = 1,
    top: Colour = (238, 238, 119),
    bottom: Colour = (255, 119, 119),
    outline: Colour = (136, 0, 0),
) -> pygame.Surface:
    """A banner word in the style of the pyExodus title art: the top half of
    each letter in ``top``, the bottom half in ``bottom``, a one-pixel
    ``outline`` all round. ``stretch`` enlarges the letters before the
    outline goes on; ``scale`` is the size of one finished pixel."""
    ink = {
        (x * stretch + i, y * stretch + j)
        for x, y in font.ink(text)
        for i in range(stretch)
        for j in range(stretch)
    }
    w = font.width(text) * stretch + 2
    h = font.height * stretch + 2
    surf = pygame.Surface((w * scale, h * scale), pygame.SRCALPHA)
    for x, y in ink:
        surf.fill(outline, (x * scale, y * scale, 3 * scale, 3 * scale))
    half = font.height * stretch // 2
    for x, y in ink:
        surf.fill(top if y < half else bottom, ((x + 1) * scale, (y + 1) * scale, scale, scale))
    return surf


def _face(height: int, top: int, data: str) -> dict[str, tuple[str, ...]]:
    """Parse ``char row row ...`` lines; rows start ``top`` rows down and the
    grid is padded with blank rows to ``height``."""
    out: dict[str, tuple[str, ...]] = {}
    for line in data.strip().splitlines():
        ch, *rows = line.split()
        blank = "." * len(rows[0])
        grid = [blank] * top + rows
        grid += [blank] * (height - len(grid))
        out[ch] = tuple(grid)
    return out


